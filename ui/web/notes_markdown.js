/* Разбор простого Markdown из заметки — чистая функция, без DOM.
 *
 * Вынесена отдельным файлом не ради порядка, а ради проверки: её можно
 * вызвать в node, без браузера и без пульта (`tests/notes_markdown.mjs`).
 * Наружу она отдаёт только данные — куски текста с признаками «жирный» и
 * «курсив», — а узлы страницы собирает pult.js. Никакого innerHTML:
 * текст из файла попадает в страницу только через textContent.
 *
 * Понимаем ровно то, что пишет модель в core/notes.py: абзацы, списки
 * «- » и «1. », заголовки `###` внутри записи, `**жирный**`, `*курсив*`
 * и свёрнутый callout `> [!quote]-`. Остальное — как обычный текст.
 */

/* --- Внутри строки: **жирный** и *курсив* --------------------------------- */

/* Ближайшая одиночная `*` — та, что не входит в пару `**`. */
function одиночнаяЗвезда(текст, искать) {
  for (let i = искать; i < текст.length; i++) {
    if (текст[i] !== '*') continue;
    if (текст[i + 1] === '*') { i += 1; continue; }  // это часть жирной пары
    return i;
  }
  return -1;
}

/* Ищем ближайшую из двух пар скобок и идём дальше. Разбор одним проходом,
   а не тремя регулярками по очереди: иначе `**жирный**` разобрался бы как
   пустая пара плюс курсив.
   Знак без пары — не разметка, а текст: голос диктует «5 * 3 = 15», и съеденный
   нами знак молча портил бы его мысль. Вложенности (`*курсив*` внутри
   `**жирного**`) не разбираем — модель её не пишет, а лишний код в пульте
   хозяину ни к чему. */
/* Ссылка Markdown `[имя](адрес)` или `[имя](<адрес с пробелами>)` — в пульте
   только имя. Разбор в заметки пишет так ссылку на документ: в Obsidian она
   открывает файл, а в пульте адрес `file:///…` был бы просто мусором, и
   кликабельной её здесь делать нельзя — пульт видит вся сеть. */
const ССЫЛКА_МД = /\[([^\]\n]+)\]\((?:<[^>\n]*>|[^)\s]*)\)/g;

function разобратьСтроку(строка) {
  const куски = [];
  const текст = String(строка == null ? '' : строка).replace(ССЫЛКА_МД, '$1');
  const простой = { жирный: false, курсив: false };
  let начало = 0;
  let искать = 0;
  for (;;) {
    const жирныйЗнак = текст.indexOf('**', искать);
    const курсивЗнак = одиночнаяЗвезда(текст, искать);
    // Из двух мест берём то, что ближе: иначе `**жирный**` нашёлся бы, а
    // курсив внутри него — раньше, и разметка бы перепуталась.
    let знак = -1;
    let жирный = false;
    if (жирныйЗнак >= 0 && (курсивЗнак < 0 || жирныйЗнак <= курсивЗнак)) {
      знак = жирныйЗнак;
      жирный = true;
    } else if (курсивЗнак >= 0) {
      знак = курсивЗнак;
    }
    if (знак < 0) break;
    const скобки = жирный ? '**' : '*';
    const закрывающий = текст.indexOf(скобки, знак + скобки.length);
    if (закрывающий < 0) {
      // Пары нет — оставляем знак текстом и ищем дальше.
      искать = знак + скобки.length;
      continue;
    }
    if (знак > начало) куски.push({ текст: текст.slice(начало, знак), ...простой });
    куски.push({ текст: текст.slice(знак + скобки.length, закрывающий),
                 жирный: жирный, курсив: !жирный });
    начало = закрывающий + скобки.length;
    искать = начало;
  }
  if (начало < текст.length) куски.push({ текст: текст.slice(начало), ...простой });
  return куски.length ? куски : [{ текст: '', ...простой }];
}

/* --- Блоки: абзацы, списки, заголовки, цитаты ---------------------------- */

const ЗАГОЛОВОК = /^(\#{1,6})\s+(.*)$/;
const ПУНКТ = /^(\s*)([-*+]|\d+[.)])\s+(.*)$/;
const ЦИТАТА = /^\s*>\s?(.*)$/;
const CALLOUT = /^\[!quote\][-+]?\s*(.*)$/;

function сложитьКуски(куски) {
  return куски.map((кусок) => кусок.текст).join('');
}

/* `текст` — причёсанное тело записи. Возвращает массив блоков:
   {вид: 'абзац'|'заголовок'|'список'|'цитата', ...}. Всё остальное, что
   не подошло под правила выше, приходит абзацем и рисуется как есть. */
function разобратьМаркдаун(текст) {
  const строки = String(текст == null ? '' : текст).split(/\r?\n/);
  const блоки = [];
  // Три «открытых» блока: незакрытая строка абзаца, список и цитата. Каждый
  // закрывается пустой строкой или другим видом блока — так границы между
  // ними и не слипаются, и не теряются.
  let абзац = null;
  let пункт = null;
  let цитата = null;

  const закрытьАбзац = () => { if (абзац) { блоки.push(абзац); абзац = null; } };
  const закрытьПункт = () => { if (пункт) { блоки.push(пункт); пункт = null; } };
  const закрытьЦитату = () => { if (цитата) { блоки.push(цитата); цитата = null; } };
  const закрытьВсё = () => { закрытьАбзац(); закрытьПункт(); закрытьЦитату(); };

  for (const строка of строки) {
    if (!строка.trim()) { закрытьВсё(); continue; }

    const заголовок = ЗАГОЛОВОК.exec(строка);
    if (заголовок && !/^\s/.test(строка)) {
      закрытьВсё();
      блоки.push({ вид: 'заголовок',
                   уровень: Math.max(3, заголовок[1].length),
                   куски: разобратьСтроку(заголовок[2]) });
      continue;
    }

    const строкаЦитаты = ЦИТАТА.exec(строка);
    if (строкаЦитаты) {
      закрытьАбзац();
      закрытьПункт();
      const внутри = строкаЦитаты[1];
      const вызов = CALLOUT.exec(внутри);
      if (вызов) {
        // Заголовок callout — его имя («Как было сказано»). Внутрь текста
        // он не входит: это подпись блока, а не первая строка мысли.
        закрытьЦитату();
        цитата = { вид: 'цитата', заголовок: вызов[1].trim(), куски: [] };
        continue;
      }
      if (!цитата) цитата = { вид: 'цитата', заголовок: '', куски: [] };
      if (внутри.trim()) цитата.куски.push(...разобратьСтроку(внутри));
      continue;
    }

    const строкаПункта = ПУНКТ.exec(строка);
    if (строкаПункта) {
      закрытьАбзац();
      закрытьЦитату();
      const нумерованный = /\d/.test(строкаПункта[2]);
      if (!пункт || пункт.нумерованный !== нумерованный) {
        закрытьПункт();
        пункт = { вид: 'список', нумерованный, пункты: [] };
      }
      пункт.пункты.push(разобратьСтроку(строкаПункта[3]));
      continue;
    }

    // Обычный абзац. Соседние строки склеиваем в один абзац, как это делает
    // Obsidian: перенос строки посреди фразы рвал бы мысль на две. Пробел
    // между ними невидим, он только в разметке — на экране его не будет.
    закрытьПункт();
    закрытьЦитату();
    const куски = разобратьСтроку(строка);
    if (абзац) {
      абзац.куски.push({ текст: ' ', жирный: false, курсив: false }, ...куски);
    } else {
      абзац = { вид: 'абзац', куски };
    }
  }
  закрытьВсё();
  return блоки;
}

/* Плоский текст блока — для подсказок и проверок в node. */
function блокВСтроку(блок) {
  if (блок.вид === 'заголовок') return '#'.repeat(блок.уровень) + ' ' + сложитьКуски(блок.куски);
  if (блок.вид === 'цитата') return '> ' + сложитьКуски(блок.куски);
  if (блок.вид === 'список') {
    return блок.пункты.map((пункт, index) =>
      (блок.нумерованный ? (index + 1) + '. ' : '- ') + сложитьКуски(пункт)).join('\n');
  }
  return сложитьКуски(блок.куски);
}

/* Для node: там нет окна, и модуль не под рукой. */
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { разобратьМаркдаун, разобратьСтроку, блокВСтроку };
}
