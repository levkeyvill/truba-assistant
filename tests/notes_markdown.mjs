// Разбор Markdown заметки проверяется в node, без браузера: функция чистая
// и в ui/web/notes_markdown.js ничего не читает с диска и не трогает DOM.
// Запуск: `node tests/notes_markdown.mjs` (из unittest — test_notes_pult.py).
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import assert from 'node:assert/strict';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const { разобратьМаркдаун, разобратьСтроку, блокВСтроку } = require(
  join(here, '..', 'ui', 'web', 'notes_markdown.js'));

const виды = (блоки) => блоки.map((блок) => блок.вид);
const текст = (блоки) => блоки.map(блокВСтроку).join('\n');

// --- Абзацы ---------------------------------------------------------------

assert.deepEqual(виды(разобратьМаркдаун('Просто одна фраза.')), ['абзац']);
assert.equal(текст(разобратьМаркдаун('Первая.\nВторая.')), 'Первая. Вторая.',
  'перенос строки внутри абзаца склеивается в пробел, как в Obsidian');
assert.deepEqual(виды(разобратьМаркдаун('Первый.\n\nВторой.')), ['абзац', 'абзац'],
  'пустая строка разделяет абзацы');
assert.deepEqual(разобратьМаркдаун(''), []);
assert.deepEqual(разобратьМаркдаун(null), []);
assert.deepEqual(виды(разобратьМаркдаун('   \n\n  ')), [], 'пустые строки не блоки');

// --- Списки ---------------------------------------------------------------

const маркеры = разобратьМаркдаун('- первое\n- второе');
assert.deepEqual(виды(маркеры), ['список']);
assert.equal(маркеры[0].нумерованный, false);
assert.deepEqual(маркеры[0].пункты, [разобратьСтроку('первое'), разобратьСтроку('второе')]);
assert.equal(текст(маркеры), '- первое\n- второе');

const номера = разобратьМаркдаун('1. раз\n2. два');
assert.equal(номера[0].нумерованный, true);
assert.equal(текст(номера), '1. раз\n2. два');

// Список после абзаца и перед ним: границы не слипаются.
assert.deepEqual(виды(разобратьМаркдаун('Мысль.\n- пункт')), ['абзац', 'список']);
assert.deepEqual(виды(разобратьМаркдаун('- пункт\nМысль.')), ['список', 'абзац']);
// Маркеры меняются — это два разных списка, а не один смешанный.
assert.deepEqual(виды(разобратьМаркдаун('- раз\n1. два')), ['список', 'список']);

// --- Жирный и курсив ------------------------------------------------------

assert.deepEqual(разобратьСтроку('**жирный**'),
  [{ текст: 'жирный', жирный: true, курсив: false }]);
assert.deepEqual(разобратьСтроку('*курсив*'),
  [{ текст: 'курсив', жирный: false, курсив: true }]);
assert.deepEqual(разобратьСтроку('**всё**'),
  [{ текст: 'всё', жирный: true, курсив: false }]);
assert.deepEqual(разобратьСтроку('до **жирно** после'),
  [{ текст: 'до ', жирный: false, курсив: false },
   { текст: 'жирно', жирный: true, курсив: false },
   { текст: ' после', жирный: false, курсив: false }]);
// Несомкнутая пара не должна съесть текст и не должна зациклиться.
assert.equal(разобратьСтроку('**не закрыто').map((к) => к.текст).join(''),
  '**не закрыто');
assert.equal(разобратьСтроку('одиночный * знак').map((к) => к.текст).join(''),
  'одиночный * знак');
// А вот пара `* … *` — разметка: так же трактует её и сам Obsidian.
assert.deepEqual(разобратьСтроку('2 * 3 * 4'),
  [{ текст: '2 ', жирный: false, курсив: false },
   { текст: ' 3 ', жирный: false, курсив: true },
   { текст: ' 4', жирный: false, курсив: false }]);
assert.equal(разобратьСтроку('***').map((к) => к.текст).join(''), '***');
assert.equal(разобратьСтроку('').map((к) => к.текст).join(''), '');
// Курсив и жирный рядом: пары не должны склеиться в одну.
assert.deepEqual(разобратьСтроку('*а* **б**'),
  [{ текст: 'а', жирный: false, курсив: true },
   { текст: ' ', жирный: false, курсив: false },
   { текст: 'б', жирный: true, курсив: false }]);

// --- Заголовки внутри записи ---------------------------------------------

// core/notes.py опускает `#` и `##` до `###`, иначе разбор принял бы их
// за новую запись. Пусть и в записи они рисуются подзаголовком.
const под = разобратьМаркдаун('### Мысль\nтекст');
assert.deepEqual(виды(под), ['заголовок', 'абзац']);
assert.equal(под[0].уровень, 3);
assert.equal(под[0].куски[0].текст, 'Мысль');
// `#` внутри записи не должен выпадать из оформления.
assert.equal(разобратьМаркдаун('# Раз')[0].уровень, 3);

// --- Callout --------------------------------------------------------------

const цитата = разобратьМаркдаун('> [!quote]- Как было сказано\n> ровным текстом');
assert.deepEqual(виды(цитата), ['цитата']);
assert.equal(цитата[0].заголовок, 'Как было сказано');
assert.equal(цитата[0].куски.map((к) => к.текст).join(''), 'ровным текстом',
  'название callout не попадает в текст мысли');
// Обычная цитата без callout: заголовка нет, текст на месте.
assert.equal(разобратьМаркдаун('> просто')[0].заголовок, '');
// Callout закрывается пустой строкой, следующий абзац — отдельный блок.
assert.deepEqual(виды(разобратьМаркдаун('> цитата\n\nпосле')), ['цитата', 'абзац']);

// --- Смешанный текст ------------------------------------------------------

const смесь = разобратьМаркдаун(
  'Первая **мысль**.\n\n- пункт один\n- пункт два\n\n> [!quote]- Как было сказано\n> сырое');
assert.deepEqual(виды(смесь), ['абзац', 'список', 'цитата']);
assert.equal(текст(смесь), 'Первая мысль.\n- пункт один\n- пункт два\n> сырое');

// Метка HTML не должна превращаться в разметку: всё, что не под правила
// выше, приходит абзацем и рисуется текстом.
assert.deepEqual(виды(разобратьМаркдаун('<script>alert(1)</script>')), ['абзац']);

process.stdout.write('Markdown notes OK: абзацы, списки, **жирный**, *курсив*, ###, callout.\n');
