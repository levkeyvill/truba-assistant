/* Дождаться, пока допишутся цепочки промисов (опрос ходит через await). */
const тик = () => new Promise(готово => setImmediate(готово));
async function переждать(раз = 4) {
  for (let шаг = 0; шаг < раз; шаг++) await тик();
}

/* Блок «Качественные голоса» в том виде, в каком его рисует форма.
   `железоДанные` кладёт сама `показатьГолоса` — кнопка смотрит на них, чтобы
   знать, стоят ли библиотеки; здесь делаем то же, раз `показатьГолоса` тянет за
   собой ещё железо и движки. */
function блок(данные) {
  const эл = {
    железоДанные: данные,
    железоГолоса: узел('button'),
    железоГолосаСтатус: узел('span'),
    голосаПолоса: узел('div'),
    голосаБибПолоса: узел('div'),
    железоСовет: { voice: 'higgs' },
    голосаРяды: {
      higgs: { модель: 'higgs', узел: узел('label'), отметка: узел('input'), состояние: узел('span') },
      espeech: { модель: 'espeech', узел: узел('label'), отметка: узел('input'), состояние: узел('span') },
    },
  };
  api.задатьФорму(эл);
  api.голосаСостояния(эл, данные);
  return эл;
}

/* Только запросы нужного маршрута: опрос ходит в фон и в счёт не идёт. */
function запросы(адрес) {
  return S.запросы.filter(з => з.адрес === адрес);
}


/* --- Подписи моделей: размеры настоящие, «1,5 ГБ» больше не врёт ----------- */
{
  const веса = await new Function(вырезатьСписок('ВЕСА_ГОЛОСОВ')
    + '\nreturn ВЕСА_ГОЛОСОВ;')();
  const подписи = Object.fromEntries(веса.map(([модель, имя, подпись]) => [модель, подпись]));
  // Две цифры у Higgs — разные вещи (файл и видеокарта), и подпись это говорит.
  assert.match(подписи.higgs, /скачать 9,3 ГБ, на видеокарте 4,3 ГБ/);
  assert.match(подписи.espeech, /скачать 2,7 ГБ/);
  assert.doesNotMatch(pult, /1,5 ГБ/,
    'старый размер ESpeech в пульте остаться не должен');
  // Те же цифры — в выборе движка, где хозяин и выбирает, что качать.
  // Подписи движков короткие (длинные обрезались в закрытом списке, 02.10),
  // а размеры — в блоке «Качественные голоса», на который ссылается подсказка.
  assert.match(pult, /\['higgs', 'Higgs · по образцу'\]/);
  assert.match(pult, /\['espeech', 'ESpeech · по образцу'\]/);
  assert.match(pult, /Сколько качать и сколько займёт на видеокарте — в «Качественных голосах»/);
}


