  assert.ok(api.голосаИдёт(), 'установка — тоже повод спрашивать');
  // Установка кончилась — таймер снимает себя сам.
  S.статус = { ok: true, installed: true, weights: {}, download: null,
    libs: { active: false, done: true } };
  const паузный = [...S.таймеры.entries()].find(([, т]) => т.пауза === ПАУЗА);
  S.таймеры.delete(паузный[0]);
  паузный[1].что();
