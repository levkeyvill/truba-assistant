/* --- Полоса: проценты, очередь и «Отменить» -------------------------------- */
{
  const куда = узел('div');
  api.голосаПолоса(куда, { active: true, model: 'higgs', title: 'Higgs',
    done: 2.1e9, total: 9.3e9, queue: ['espeech'], error: '' });
  assert.equal(куда.hidden, false, 'идёт загрузка — полоса видна');
  // Надпись: имя качаемой модели, сколько уже и сколько всего, процент.
  // Единица после первого числа повторяется («2,1 ГБ из 9,3 ГБ») — она
  // необязательна в проверке, смысл в числах и проценте.
  assert.match(куда.текст(), /Качаю Higgs: 2,1( ГБ)? из 9,3 ГБ \(23 %\)/);
  const полоса = найти(куда, 'голоса-полоса');
  assert.ok(полоса, 'полоска нарисована');
  assert.equal(полоса.атрибуты['aria-valuenow'], '23');
  assert.equal(полоса.дети[0].style.width, '23.0%', 'заливка на 23 %');
  assert.match(куда.текст(), /дальше: ESpeech/, 'очередь видна хозяину');
  const отменить = куда.дети.flatMap(с => с.дети || []).concat(куда.дети)
    .find(с => с.textContent === 'Отменить');
  assert.ok(отменить, 'кнопка «Отменить» есть');
  S.запросы.length = 0;
  S.статус = { ok: true, installed: true, weights: {}, download: null };
  await api.голосаОтменить(отменить);
  const отмена = запросы('/api/voices/download/cancel');
  assert.equal(отмена.length, 1, '«Отменить» останавливает скачивание');
  assert.equal(отмена[0].метод, 'POST');
}


