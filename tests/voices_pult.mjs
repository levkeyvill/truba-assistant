/* --- Опрос: таймер живёт ровно пока идёт загрузка -------------------------- */
{
  S.запросы.length = 0;
  S.таймеры.clear();
  S.скрыта = false;
  const тики = () => [...S.таймеры.values()].filter(т => т.пауза === ПАУЗА);
  S.статус = { ok: true, installed: true, weights: {},
    download: { active: true, model: 'higgs', done: 1e9, total: 9.3e9 } };
  api.голосаОпросВключить();
  await переждать();
  assert.equal(запросы('/api/voices/status').length, 1, 'первый вопрос — сразу');
  assert.equal(тики().length, 1, 'пока качают, опрос продолжается');
  assert.ok(api.взятьХод().active, 'ход загрузки виден и Панели');
  // Качать кончилось — опрос себя снимает. Таймер срабатывает сам, поэтому
  // перед вызовом убираем его из подмены — иначе он остался бы «висеть».
  S.статус = { ok: true, installed: true, weights: { higgs: true },
    download: { active: false, finished: true } };
  const паузный = [...S.таймеры.entries()].find(([, т]) => т.пауза === ПАУЗА);
  S.таймеры.delete(паузный[0]);
  паузный[1].что();
  await переждать();
  assert.equal(запросы('/api/voices/status').length, 2);
  assert.equal(тики().length, 0, 'загрузка кончилась — таймер снят');
  api.голосаОпросВыключить();
  S.таймеры.clear();
}


