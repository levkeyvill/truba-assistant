// Качественные голоса в пульте: выбор моделей с размерами, кнопка «Скачать
// выбранное» / «Установить выбранное», полоса скачивания с «Отменить», опрос
// раз в две секунды и строка под карточкой голоса на Панели.
// Функции вырезаются из `pult.js` целиком и живут в подставном окружении:
// сервер, DOM, таймеры и `window.confirm` — подмены, поэтому ни голоса, ни
// сети, ни настоящих моделей тут не нужно.
// Запуск: `node tests/voices_pult.mjs` (из unittest — test_voices_pult.py).
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const pult = (await readFile(new URL('../ui/web/pult.js', import.meta.url), 'utf8'))
  .replace(/\r\n/g, '\n');

/* Функция из pult.js целиком — от `function имя(` до строки `}` в начале
   строки. Именно так написан весь проект, иначе проверка проверяла бы копию. */
function вырезать(имя) {
  const начало = pult.indexOf('function ' + имя + '(');
  assert.notEqual(начало, -1, 'в pult.js нет функции ' + имя);
  const конец = pult.indexOf('\n}\n', начало);
  assert.notEqual(конец, -1, 'не нашёлся конец функции ' + имя);
  // `await` есть только у `async function` — без этого слова из оглавления
  // получилась бы обычная функция и сломанный синтаксис.
  const началоСлова = pult.lastIndexOf('\n', начало) + 1;
  const началоAsync = pult.startsWith('async function ', началоСлова) ? началоСлова : начало;
  return pult.slice(началоAsync, конец + 3);
}

/* Аналогично для `const ИМЯ = [...]`: список моделей с подписями живёт
   константой, и проверять надо именно её, а не её копию здесь. */
function вырезатьСписок(имя) {
  const начало = pult.indexOf('const ' + имя + ' = [');
  assert.notEqual(начало, -1, 'в pult.js нет списка ' + имя);
  const конец = pult.indexOf('\n];\n', начало);
  assert.notEqual(конец, -1, 'не нашёлся конец списка ' + имя);
  return pult.slice(начало, конец + 4);
}

