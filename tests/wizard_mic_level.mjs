// Полоска уровня выбранного микрофона на шаге 4 мастера: запрос сам называет
// микрофон и вход, опрос идёт и при выключенном голосе, а при смене выбора,
// уходе со слоя и уходе из окна он останавливается. Функции вырезаются из
// `pult.js` целиком и живут в подставленном окружении: сервер, устройства и
// таймеры — подмены, ни микрофона, ни сети тут не нужно.
// Запуск: `node tests/wizard_mic_level.mjs` (из unittest — test_wizard_mic_level.py).
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const pult = (await readFile(new URL('../ui/web/pult.js', import.meta.url), 'utf8'))
  .replace(/\r\n/g, '\n');

function вырезать(имя) {
  const начало = pult.indexOf('function ' + имя + '(');
  assert.notEqual(начало, -1, 'в pult.js нет функции ' + имя);
  const конец = pult.indexOf('\n}\n', начало);
  assert.notEqual(конец, -1, 'не нашёлся конец функции ' + имя);
  const началоСлова = pult.lastIndexOf('\n', начало) + 1;
  const началоAsync = pult.startsWith('async function ', началоСлова) ? началоСлова : начало;
  return pult.slice(началоAsync, конец + 3);
}

const ИМЕНА = ['число', 'звукЧисло', 'звукЖива', 'звукУровеньПоказать', 'мастерЖива',
  'мастерУровеньАдрес', 'мастерУровеньПоказать', 'мастерУровеньОдинРаз',
  'мастерУровеньВключить', 'мастерУровеньВыключить'];

function узел(значение = '') {
  const классы = new Set();
  return {
    value: значение, disabled: false, hidden: false, isConnected: true,
    textContent: '', dataset: {}, style: {},
    классы,
    classList: {
      add: имя => классы.add(имя),
      remove: имя => классы.delete(имя),
      toggle: (имя, есть) => (есть ? классы.add(имя) : классы.delete(имя)),
      contains: имя => классы.has(имя),
    },
  };
}

/* Страница без окна браузера: таймеры наши, `document.hidden` — подмена. */
const S = {
  запросы: [],
  ответы: {},
  таймеры: new Map(),
  следующий: 1,
  скрыта: false,
  мастерОткрыт: true,
  мастерШаг: 4,
  мастерШаги: {},
  настройкиЖивы: () => false,
  fetch: async (адрес, опции) => {
    S.запросы.push(адрес);
    const ответ = S.ответы[адрес.split('?')[0]];
    if (ответ) return ответ;
    return { ok: true, status: 200, json: async () => ({ ok: true, level: 0.4 }) };
  },
  setTimeout: (что, пауза) => {
    const номер = S.следующий++;
    S.таймеры.set(номер, { что, пауза });
    return номер;
  },
  clearTimeout: номер => S.таймеры.delete(номер),
};

/* Прогнать ожидающие таймеры по одному разу: так видно и паузу между
   запросами, и что после остановки таймеров не осталось. */
async function тик(раз = 1) {
  for (let шаг = 0; шаг < раз; шаг++) {
    // Опрос асинхронный: сначала даём ему дописать текущий запрос, только
    // потом смотрим, поставлен ли следующий таймер.
    await new Promise(готово => setImmediate(готово));
    const пара = [...S.таймеры.entries()][0];
    if (!пара) return;
    S.таймеры.delete(пара[0]);
    await пара[1].что();
  }
}

const ПОДСТАНОВКА = `
  const мастерОткрыт = S.мастерОткрыт;
  let мастерШаг = S.мастерШаг;
  const мастерШаги = S.мастерШаги;
  const настройкиЖивы = S.настройкиЖивы;
  const fetch = (адрес, опции) => S.fetch(адрес, опции);
  const setTimeout = (что, пауза) => S.setTimeout(что, пауза);
  const clearTimeout = номер => S.clearTimeout(номер);
  const document = { get hidden() { return S.скрыта; } };
  const МАСТЕР_УРОВЕНЬ_ПАУЗА = 400;
  let мастерУровеньТаймер = null;
  let мастерУровеньПроход = 0;
  // Номер шага в pult.js — переменная уровня страницы, и проверка шага 4
  // («уже не тот шаг») читает именно её.
  function уйтиНаШаг(номер) { мастерШаг = номер; }
`;

const api = new Function('S', ПОДСТАНОВКА + ИМЕНА.map(вырезать).join('\n')
  + '\nreturn { мастерУровеньВключить, мастерУровеньВыключить,'
  + ' мастерУровеньОдинРаз, мастерУровеньАдрес, уйтиНаШаг };')(S);

function шаг(имя = 'Новый микрофон (USB)', вход = '0') {
  // Объект шагов в подстановке — тот же, что в `S`: пересоздавать его нельзя.
  for (const ключ of Object.keys(S.мастерШаги)) delete S.мастерШаги[ключ];
  api.уйтиНаШаг(4);
  const эл = {
    mic_name: узел(имя), mic_channel: узел(вход), speaker_name: узел(''),
    уровень: узел(''), уровеньFill: узел(''), уровеньПодпись: узел(''),
  };
  S.мастерШаги[4] = эл;
  return эл;
}

function проверитьУровень(эл, доля, текст) {
  assert.equal(эл.уровеньFill.style.width, (доля * 100).toFixed(1) + '%', текст);
}

/* --- Запрос называет выбранный микрофон и вход, даже при выключенном голосе --- */
{
  S.запросы.length = 0;
  S.таймеры.clear();
  S.ответы = { '/api/audio/level': { ok: true, status: 200,
    json: async () => ({ ok: true, level: 0.62, source: 'measure' }) } };
  const эл = шаг('Новый микрофон (USB)', '1');
  await api.мастерУровеньОдинРаз(эл);
  assert.equal(S.запросы.length, 1, 'полоска должна спросить сразу, без голоса');
  const адрес = S.запросы[0];
  assert.match(адрес, /^\/api\/audio\/level\?/, 'опрос мастера с параметром выбора');
  assert.match(адрес, /preview=1/);
  assert.match(адрес, /mic_name=%D0%9D%D0%BE%D0%B2%D1%8B%D0%B9/,
    'имя микрофона должно уйти в запрос');
  assert.match(адрес, /mic_channel=1/, 'вход тоже должен уйти в запрос');
  проверитьУровень(эл, 0.62, 'уровень выбранного микрофона рисуется как есть');
}

/* --- Имя с пробелами и знаками не ломает адрес --- */
{
  const эл = шаг('Микрофон (2-ой USB) & другое');
  const адрес = api.мастерУровеньАдрес(эл);
  assert.ok(!адрес.includes(' '), 'пробелы должны быть закодированы');
  assert.match(адрес, /%26/, 'знак «&» не должен ломать запрос');
}

/* --- Не выбран ничего: запрос всё равно идёт, замер возьмёт системный --- */
{
  const эл = шаг('');
  assert.match(api.мастерУровеньАдрес(эл), /mic_name=&mic_channel=0/);
}

/* --- Сервер объяснил, почему полоска молчит: показываем причину --- */
{
  const эл = шаг('Занятый микрофон');
  S.ответы = { '/api/audio/level': { ok: true, status: 200, json: async () => ({
    ok: false, error: 'микрофон «Занятый микрофон» не даёт замерить уровень: занято' }) } };
  await api.мастерУровеньОдинРаз(эл);
  assert.match(эл.уровеньПодпись.textContent, /занято/,
    'хозяин должен видеть причину, а не тишину чужого микрофона');
  проверитьУровень(эл, 0, 'при отказе полоса пуста');
}

/* --- Опрос сам ограничен частотой и идёт по своему таймеру --- */
{
  S.запросы.length = 0;
  S.таймеры.clear();
  S.ответы = {};
  const эл = шаг();
  api.мастерУровеньВключить(эл);
  assert.equal(S.запросы.length, 1, 'первый запрос без ожидания');
  await тик();
  assert.equal(S.запросы.length, 2);
  const пауза = [...S.таймеры.values()][0].пауза;
  assert.ok(пауза >= 300 && пауза <= 600,
    'между замерами должно быть около 0,3–0,6 с, а не 150 мс как у вкладки');
}

/* --- Уход со слоя мастера останавливает опрос --- */
{
  S.запросы.length = 0;
  S.таймеры.clear();
  const эл = шаг();
  api.мастерУровеньВключить(эл);
  assert.equal(S.запросы.length, 1);
  // Хозяин ушёл на другой шаг: слой мастера больше не этот.
  api.уйтиНаШаг(5);
  await тик();
  assert.equal(S.запросы.length, 1, 'после ухода со слоя запросов быть не должно');
  assert.equal(S.таймеры.size, 0, 'таймер должен быть снят');
}

/* --- Уход из окна останавливает опрос --- */
{
  S.запросы.length = 0;
  S.таймеры.clear();
  const эл = шаг();
  api.мастерУровеньВключить(эл);
  assert.equal(S.запросы.length, 1);
  S.скрыта = true;
  await тик();
  assert.equal(S.запросы.length, 1, 'скрытое окно не опрашивает сервер');
  assert.equal(S.таймеры.size, 0);
  // Вернулся в окно на шаг 4 — полоска снова идёт.
  S.скрыта = false;
  api.мастерУровеньВключить(эл);
  assert.equal(S.запросы.length, 2, 'возвращение в окно снова спрашивает уровень');
  api.мастерУровеньВыключить();
  S.таймеры.clear();
}

/* --- Смена микрофона начинает опрос заново и с новым именем --- */
{
  S.запросы.length = 0;
  S.таймеры.clear();
  const эл = шаг();
  api.мастерУровеньВключить(эл);
  эл.mic_name.value = 'Другой микрофон';
  api.мастерУровеньВключить(эл);
  // Старый таймер снят сразу, а новый ставится после ответа: ждём ответа.
  assert.equal(S.таймеры.size, 0, 'таймер прошлого выбора снят сразу');
  await тик();
  // Ровно один опрос: проход от прошлого выбора больше не ставит таймер.
  assert.equal(S.таймеры.size, 1, 'по новому выбору опрос продолжается, старый снят');
  await тик();
  assert.match(S.запросы[S.запросы.length - 1], /%D0%94%D1%80%D1%83%D0%B3%D0%BE%D0%B9/,
    'опрос пошёл по новому выбору');
  api.мастерУровеньВыключить();
  S.таймеры.clear();
}

/* --- Смена входа тоже меняет запрос --- */
{
  S.запросы.length = 0;
  const эл = шаг();
  эл.mic_channel.value = '1';
  await api.мастерУровеньОдинРаз(эл);
  assert.match(S.запросы[0], /mic_channel=1/);
}

/* --- Голос не трогаем: в списке запросов не должно быть переключений --- */
{
  S.запросы.length = 0;
  S.таймеры.clear();
  const эл = шаг();
  api.мастерУровеньВключить(эл);
  await тик();
  api.мастерУровеньВыключить();
  S.таймеры.clear();
  assert.equal(S.запросы.filter(а => а.indexOf('/api/voice/toggle') === 0).length, 0,
    'полоска не включает и не выключает голос');
  assert.equal(S.запросы.filter(а => а.indexOf('/api/audio/test') === 0).length, 0,
    'полоска не пишет микрофон');
}

