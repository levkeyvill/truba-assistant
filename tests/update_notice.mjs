// Проверка плашки «вышла версия»: решение принимается по результату
// автоматической проверки, а не по одному раннему запросу `/api/about`.
//
// Живой пульт не поднимаем: `document`, `fetch` и `setTimeout` подменены,
// ответы `/api/about` задаются списком (поздний результат — со второй
// попытки). Никаких походов в GitHub и никаких нажатий «Обновить».
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const тут = dirname(fileURLToPath(import.meta.url));
const исходник = readFileSync(join(тут, '..', 'ui', 'web', 'pult.js'), 'utf8');

let счётчик = 0;

// Вырезаем из пульта ровно те функции, что решают судьбу плашки: остальное
// (окно, меню, чат) в проверке ни при чём.
function функция(имя) {
  let начало = исходник.indexOf('function ' + имя + '(');
  assert.notEqual(начало, -1, 'нет функции ' + имя);
  // `async` перед словом function — без него тело осталось бы без ожидания.
  if (исходник.slice(начало - 6, начало) === 'async ') начало -= 6;
  // Считаем скобки: тело может быть в одну строку, как `обнРешениеПроверки`.
  let глубина = 0;
  for (let i = начало; i < исходник.length; i++) {
    if (исходник[i] === '{') глубина++;
    else if (исходник[i] === '}' && --глубина === 0) return исходник.slice(начало, i + 1);
  }
  assert.fail('не нашли конец ' + имя);
}

function объявление(имя) {
  const начало = исходник.indexOf(имя);
  assert.notEqual(начало, -1, 'нет объявления ' + имя);
  return исходник.slice(начало, исходник.indexOf('\n', начало));
}

/* Подделки: узел без DOM, тело без документа, ответы `/api/about` — из
   заданного списка. Всё временное, живых данных здесь нет. */
const ПОДДЕЛКА = `
function узел() {
  return {
    textContent: '', дети: [], удалён: false, обработчики: {},
    setAttribute() {},
    set className(з) { this.класс = з; },
    get className() { return this.класс; },
    append(...у) { this.дети.push(...у); },
    addEventListener(с, о) { this.обработчики[с] = о; },
    remove() { this.удалён = true; },
    click() { if (this.обработчики.click) this.обработчики.click(); },
  };
}
const добавленные = [];
const document = {
  createElement: () => узел(),
  querySelectorAll: () => [],
  body: { appendChild: (эл) => добавленные.push(эл) },
};
const паузы = [];
/* Пауза без настоящего ожидания: делегат отпускаем сразу, но считаем, сколько
   раз пульт ждал. Иначе проверка висела бы две минуты по-настоящему. */
function setTimeout(дело, мс) { паузы.push(мс); queueMicrotask(дело); return 0; }
let обнЗначокНужно = false;
let обнПроверка = null;
function обнПоказатьЗначок(нужно) { обнЗначокНужно = !!нужно; }
function открыть(имя) { открытРаздел = имя; }
let открытРаздел = null;
`;

/* Каждый сценарий — свой файл со своими переменными: как в живом пульте, где
   состояние живёт ровно один запуск. */
async function пуск(ответы) {
  const тело = [
    ПОДДЕЛКА,
    'let очередь = ' + JSON.stringify(ответы) + ';',
    'async function fetch(адрес) {',
    '  if (!очередь.length) throw new Error("запросов больше быть не должно: " + адрес);',
    '  const шаг = очередь.shift();',
    '  if (шаг === "сбой") throw new Error("нет связи");',
    '  return { ok: шаг.ok !== false, json: async () => шаг.body };',
    '}',
    объявление('let обнПлашкаПоказана'),
    'let обнПлашкаУзел = null;',
    'const ОБН_ПОПЫТКИ = 10;',
    'const ОБН_ПАУЗА = 10;',
    функция('обнРешениеПроверки'),
    функция('проверитьЗначокПриЗапуске'),
    функция('обнПоказатьПлашку'),
    функция('обнСкрытьПлашку'),
    // Геттеры: кнопку нажимают уже после возврата, а состояние — живое.
    'export async function пуск() {',
    '  await проверитьЗначокПриЗапуске();',
    '  return { get точка() { return обнЗначокНужно; },',
    '           get плашка() { return обнПлашкаУзел; },',
    '           get показана() { return обнПлашкаПоказана; },',
    '           get паузы() { return паузы.length; },',
    '           get раздел() { return открытРаздел; } };',
    '}',
  ].join('\n');
  const папка = mkdtempSync(join(tmpdir(), 'truba-update-'));
  const файл = join(папка, `сценарий-${++счётчик}.mjs`);
  writeFileSync(файл, тело, 'utf8');
  // На Windows путь надо отдать как file:// — иначе node не грузит модуль.
  return import(pathToFileURL(файл).href);
}


const пустое = { body: { ok: true, update_check: true, checked: {} } };
const новая = (версия) => ({
  body: { ok: true, update_check: true,
    checked: { last: { state: 'newer', latest: версия, zip: 'z.zip' } } },
});

// 1. Позднее завершение проверки: первый ответ пустой (проверка при запуске
//    ещё не дошла до GitHub), второй — с результатом.
{
  const модуль = await пуск([пустое, новая('2.4.1')]);
  const итог = await модуль.пуск();
  assert.equal(итог.паузы, 1, 'должна быть ровно одна пауза между попытками');
  assert.equal(итог.точка, true, 'точка у «О программе» должна появиться');
  assert.ok(итог.плашка, 'плашка обязана появиться при позднем результате');
  const текст = итог.плашка.дети.map((у) => у.textContent || '').join(' ');
  assert.ok(текст.includes('2.4.1'), 'в плашке должен быть номер версии');
  assert.ok(текст.includes('О программе'), 'в плашке должна быть кнопка «О программе»');
  assert.ok(итог.плашка.дети.some((у) => у.класс === 'голос-кнопка'), 'нужна кнопка');
  assert.ok(!текст.includes('Обновить'), 'плашка не должна предлагать установку');
}

// 2. Пульт открыли после проверки: результат уже готов — с первой попытки.
{
  const модуль = await пуск([новая('2.4.2')]);
  const итог = await модуль.пуск();
  assert.equal(итог.паузы, 0, 'готовый результат не должен ждать повторного запроса');
  assert.equal(итог.точка, true);
  assert.ok(итог.плашка, 'результат позднего открытия тоже показывается');
}

// 3. Ложного уведомления быть не должно: новой версии нет.
{
  const модуль = await пуск([{ body: { ok: true, update_check: true,
    checked: { last: { state: 'latest', current: '2.4.0' } } } }]);
  const итог = await модуль.пуск();
  assert.equal(итог.плашка, null, 'при latest плашки быть не может');
  assert.equal(итог.точка, false, 'при latest точки быть не может');
}

// 4. Ошибка проверки — тоже молчание, а не «есть обновление».
{
  const модуль = await пуск([{ body: { ok: true, update_check: true,
    checked: { last: { ok: false, state: 'error', error: 'сеть' } } } }]);
  const итог = await модуль.пуск();
  assert.equal(итог.плашка, null, 'при ошибке плашки быть не может');
  assert.equal(итог.точка, false, 'при ошибке точки быть не может');
}

// 5. Проверка выключена: ждать нечего — запросов дальше первого нет.
{
  const модуль = await пуск([
    { body: { ok: true, update_check: false, checked: {} } },
  ]);
  const итог = await модуль.пуск();
  assert.equal(итог.плашка, null);
  assert.equal(итог.паузы, 0, 'выключенная проверка не должна ждать попыток');
}

// 6. Нет связи — пульт не падает и ничего не показывает.
{
  const модуль = await пуск(['сбой']);
  const итог = await модуль.пуск();
  assert.equal(итог.плашка, null);
  assert.equal(итог.точка, false);
}

// 7. Не повторять бесконечно: пока не пришёл результат — попытки идут, но не
//    больше десяти, и плашка за это время не появилась.
{
  const модуль = await пуск(Array.from({ length: 12 }, () => пустое));
  const итог = await модуль.пуск();
  assert.equal(итог.паузы, 9, 'десять попыток: девять пауз между ними');
  assert.equal(итог.плашка, null, 'без результата плашки нет');
}

// 8. Кнопка плашки ведёт в «О программе» и гасит плашку; повторного показа
//    после просмотра не будет.
{
  const модуль = await пуск([новая('2.4.3')]);
  const итог = await модуль.пуск();
  const плашка = итог.плашка;
  const кнопка = плашка.дети.find((у) => у.textContent === 'О программе');
  assert.ok(кнопка, 'кнопка «О программе» должна быть в плашке');
  кнопка.click();
  assert.equal(итог.раздел, 'программа', 'кнопка открывает «О программе»');
  assert.equal(плашка.удалён, true, 'после нажатия плашка убирается');
  assert.equal(итог.плашка, null, 'ссылки на плашку больше нет');
  assert.equal(итог.показана, true, 'дальше в этом запуске плашка не повторится');
}

console.log('плашка обновления: 8 сценариев пройдено');
