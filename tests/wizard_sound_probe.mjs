/* --- Два нажатия подряд: гонки быть не должно --- */
{
  S.запросы.length = 0;
  const эл = шаг();
  эл.mic_name.value = 'Микрофон (USB)';
  const вернуть = сервер({});
  await Promise.all([мастерПроверитьЗвук(эл), мастерПроверитьЗвук(эл)]);
  вернуть();
  const записи = S.запросы.filter(запрос => запрос.адрес === ПРОБА);
  assert.equal(записи.length, 1, 'микрофон должен записаться ровно один раз');
}

/* --- Полоска уровня встаёт на паузу на время пробы и возвращается после ---
   Проба держит микрофон три секунды, а таймер шага 4 каждые 0,4 с спрашивает
   уровень того же устройства: два захвата разом дают «устройство занято». */
{
  S.запросы.length = 0;
  S.уровеньЗапросы.length = 0;
  S.таймеры.clear();
  const эл = шаг();
  эл.mic_name.value = 'Микрофон (USB)';
  // Полоска идёт: первый замер сразу, дальше — по таймеру.
  мастерУровеньВключить(эл);
  await new Promise(готово => setImmediate(готово));
  assert.equal(S.уровеньЗапросы.length, 1,
    'до пробы полоска спрашивает уровень');
  // Проба: как только сервер отвечает на неё, проверяем, что таймер уровня
  // снят и замеров больше не идёт.
  let началоПробы = null;
  const начало = new Promise(готово => { началоПробы = готово; });
  const вернуть = сервер({ [ПРОБА]: () => { началоПробы(); return undefined; } });
  const проба = мастерПроверитьЗвук(эл);
  await начало;
  assert.equal(S.таймеры.size, 0, 'на время пробы таймер полоски снят');
  assert.equal(S.уровеньЗапросы.length, 1,
    'пока шла проба, микрофон не замеряли');
  await проба;
  // Проба кончилась — полоска обязана вернуться, иначе шаг 4 замолчит навсегда.
  await new Promise(готово => setImmediate(готово));
  assert.equal(S.уровеньЗапросы.length, 2,
    'после пробы полоска снова спрашивает уровень');
  вернуть();
  мастерУровеньВыключить();
  S.таймеры.clear();
}

/* --- Уход в другую вкладку во время пробы: полоску обратно не поднимаем --- */
{
  // Дожидаемся хвоста предыдущего сценария: его возобновленная полоска ещё
  // дописывает свой запрос, и в счётчик он попал бы не туда.
  for (let хвост = 0; хвост < 3; хвост++) await new Promise(готово => setImmediate(готово));
  S.запросы.length = 0;
  S.уровеньЗапросы.length = 0;
  S.таймеры.clear();
  const эл = шаг();
  эл.mic_name.value = 'Микрофон (USB)';
  мастерУровеньВключить(эл);
  await new Promise(готово => setImmediate(готово));
  const вернуть = сервер({});
  const проба = мастерПроверитьЗвук(эл);
  // Хозяин ушёл на другую вкладку, пока писало: вкладка скрыта — полоска
  // возвращаться не должна (иначе она сама себя разбудит).
  S.скрыта = true;
  await проба;
  await new Promise(готово => setImmediate(готово));
  assert.equal(S.уровеньЗапросы.length, 1,
    'окно скрыто — полоска не возвращается');
  S.скрыта = false;
  вернуть();
  мастерУровеньВыключить();
  S.таймеры.clear();
}

process.stdout.write('Wizard sound probe OK: the level timer pauses for the probe and '
  + 'comes back after it.\n');
