"""Пульт: правка заметок — кнопки, формы и вызовы новых маршрутов.

Страницу пульта тесты не исполняют (см. test_pult_sound_page.py), поэтому
здесь строки в `pult.js` и грабли, которые уже случались: опечатка в
кириллическом имени роняет всю страницу, а текст из заметок не должен
попадать в разметку — в нём бывает `<`.
"""

import re
import unittest
from pathlib import Path

import config

PULT = Path(config.ROOT) / "ui" / "web"

# Все три маршрута части 1: правка записи, переименование темы, новая запись.
МАРШРУТЫ = ("/api/notes/edit", "/api/notes/rename", "/api/notes/add")


def _функция(скрипт, имя):
    """Текст функции с русским именем: от заголовка до строки с `}` в нуле."""
    начало = скрипт.find("function " + имя + "(")
    if начало < 0:
        raise AssertionError("нет функции " + имя)
    конец = скрипт.find("\n}\n", начало)
    assert конец > начало, имя
    return скрипт[начало:конец]


class ПравкаЗаметокПультTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.скрипт = (PULT / "pult.js").read_text(encoding="utf-8")
        cls.стили = (PULT / "pult.css").read_text(encoding="utf-8")

    def test_маршруты_правки_вызываются(self):
        for маршрут in МАРШРУТЫ:
            with self.subTest(маршрут=маршрут):
                self.assertIn("заметкиПост('" + маршрут + "'", self.скрипт)

    def test_кнопки_на_странице(self):
        for надпись in ("Изменить", "Переименовать", "Новая запись"):
            with self.subTest(надпись=надпись):
                self.assertIn("'" + надпись + "'", self.скрипт)
        self.assertIn("'зам-изменить'", self.скрипт)
        self.assertIn(".зам-изменить", self.стили)
        # «Удалить» у записи осталась, и «Изменить» — перед ней.
        карточка = _функция(self.скрипт, "заметкиЗапись")
        self.assertLess(карточка.index("'зам-изменить'"),
                        карточка.index("'зам-убрать'"))

    def test_изменение_идёт_по_номеру_и_заголовку(self):
        правка = _функция(self.скрипт, "заметкиСохранитьЗапись")
        self.assertIn("'/api/notes/edit'", правка)
        self.assertIn("index: запись.номер", правка)
        self.assertIn("heading: запись.heading", правка)
        self.assertIn("section: выбор.раздел, topic: выбор.тема", правка)

    def test_форма_записи_меняет_тело_карточки(self):
        карточка = _функция(self.скрипт, "заметкиЗапись")
        self.assertIn("тело.appendChild(заметкиФормаЗаписи(запись))", карточка)
        форма = _функция(self.скрипт, "заметкиФормаЗаписи")
        self.assertIn("настрВвод(запись.title)", форма)
        self.assertIn("заметкиТекстПоле(запись.text)", форма)
        self.assertIn("заметкиКнопка('Сохранить', true)", форма)
        self.assertIn("заметкиКнопка('Отмена'", форма)
        # Свёрнутое «Как было сказано» под формой осталось как было.
        self.assertIn("Как было сказано", карточка)

    def test_форма_темы_берёт_подсказки_разделов(self):
        форма = _функция(self.скрипт, "заметкиФормаТемы")
        self.assertIn("настрВвод(тема.topic)", форма)
        self.assertIn("настрВвод(тема.section)", форма)
        self.assertIn("createElement('datalist')", форма)
        self.assertIn("заметкиДанные.sections", форма)
        переименование = _функция(self.скрипт, "заметкиПереименоватьТему")
        self.assertIn("'/api/notes/rename'", переименование)
        self.assertIn("new_topic: новое", переименование)
        self.assertIn("new_section: String(раздел.value || '').trim()",
                      переименование)
        # Ответ сервера — имена так, как их увидит список.
        self.assertIn("заметкиВыбранная = искомое", переименование)
        self.assertIn("заметкиНайтиТему(искомое)", переименование)

    def test_новая_запись(self):
        форма = _функция(self.скрипт, "заметкиФормаНовой")
        self.assertIn("'Заголовок, можно пусто'", форма)
        self.assertIn("заметкиКнопка('Записать', true)", форма)
        запись = _функция(self.скрипт, "заметкиЗаписатьНовую")
        self.assertIn("'/api/notes/add'", запись)
        self.assertIn("section: выбор.раздел, topic: выбор.тема", запись)

    def test_пустой_текст_не_уходит_на_сервер(self):
        for имя in ("заметкиСохранитьЗапись", "заметкиЗаписатьНовую"):
            with self.subTest(имя=имя):
                тело = _функция(self.скрипт, имя)
                self.assertIn("Текст пустой", тело)
                self.assertLess(тело.index("Текст пустой"),
                                тело.index("заметкиПост("))
        # Пустое название темы — тоже не отправляем.
        переименование = _функция(self.скрипт, "заметкиПереименоватьТему")
        self.assertLess(переименование.index("Название пустое"),
                        переименование.index("заметкиПост("))

    def test_в_формах_нет_innerHTML(self):
        # Текст заметки может содержать `<`: в разметку он попадать не должен.
        for имя in ("заметкиФормаЗаписи", "заметкиФормаТемы", "заметкиФормаНовой",
                    "заметкиТекстПоле", "заметкиФормаРяд",
                    "заметкиСохранитьЗапись", "заметкиПереименоватьТему",
                    "заметкиЗаписатьНовую", "заметкиНайтиТему"):
            with self.subTest(имя=имя):
                self.assertNotIn("innerHTML", _функция(self.скрипт, имя))

    def test_одна_форма_за_раз(self):
        # Состояние формы в одной переменной, и она общая для всех трёх форм.
        self.assertIn("let заметкиПравка = null;", self.скрипт)
        for вид in ("{вид: 'запись'", "{вид: 'тема'}", "{вид: 'новая'}"):
            with self.subTest(вид=вид):
                self.assertIn("заметкиОткрытьПравку(" + вид, self.скрипт)
        # Выбрали другую тему — прежняя форма закрылась.
        выбор = _функция(self.скрипт, "заметкиВыбрать")
        self.assertIn("заметкиПравка = null;", выбор)
        # Пока идёт сохранение, кнопки формы неактивны.
        ждать = _функция(self.скрипт, "заметкиФормаЖдать")
        self.assertIn("кнопка.disabled = true", ждать)

    def test_клавиши_в_формах(self):
        клавиши = _функция(self.скрипт, "заметкиФормаКлавиши")
        self.assertIn("'Escape'", клавиши)
        self.assertIn("'Enter'", клавиши)
        self.assertIn("событие.ctrlKey", клавиши)

    def test_в_именах_нет_латинских_букв(self):
        # Латинская буква вместо кириллической в `заметкиПравка` уронила бы
        # всю страницу заметок, а `node --check` этого не видит.
        self.assertNotIn("заметкиВыбраная", self.скрипт)
        self.assertNotIn("заметкиПравкаЗаписи", self.скрипт)
        for имя in ("заметкиПравка", "заметкиОткрытьПравку", "заметкиЗакрытьПравку",
                    "заметкиТекстПоле", "заметкиФормаРяд", "заметкиФормаКлавиши",
                    "заметкиФормаЖдать", "заметкиФормаЗаписи",
                    "заметкиФормаТемы", "заметкиФормаНовой",
                    "заметкиСохранитьЗапись", "заметкиПереименоватьТему",
                    "заметкиЗаписатьНовую", "заметкиНайтиТему"):
            with self.subTest(имя=имя):
                self.assertNotRegex(имя, r"[a-z]")

    def test_каждая_вызванная_функция_объявлена(self):
        объявлены = set(re.findall(r"function ([Ѐ-ӿ][Ѐ-ӿ\w]*)\(", self.скрипт))
        for имя in set(re.findall(r"(заметки[Ѐ-ӿ\w]*)\(", self.скрипт)):
            with self.subTest(имя=имя):
                self.assertIn(имя, объявлены)

    def test_главные_кнопки_нажимаются(self):
        # Обе кнопки должны вызывать обработчик сохранения, как и Ctrl+Enter.
        for функция, кнопка in (("заметкиФормаЗаписи", "сохранить"),
                                ("заметкиФормаТемы", "сохранить"),
                                ("заметкиФормаНовой", "записать")):
            with self.subTest(функция=функция):
                тело = _функция(self.скрипт, функция)
                self.assertIn(кнопка + ".addEventListener('click',", тело)

    def test_в_формах_одна_и_та_же_переменная(self):
        # Там же: `form.appendChild` латиницей и `форму` вместо `форма` —
        # ReferenceError при открытии формы, а `node --check` молчит.
        for функция in ("заметкиФормаЗаписи", "заметкиФормаТемы", "заметкиФормаНовой"):
            with self.subTest(функция=функция):
                тело = _функция(self.скрипт, функция)
                self.assertNotRegex(тело, r"(?<![\wЀ-ӿ])form\.")
                self.assertNotIn("форму", тело)

    def test_концы_строк_не_поменялись(self):
        # `pult.js` — CRLF, `pult.css` — LF: переводить файл целиком нельзя.
        self.assertNotIn(b"\r\n", (PULT / "pult.css").read_bytes())
        self.assertIn(b"\r\n", (PULT / "pult.js").read_bytes())


if __name__ == "__main__":
    unittest.main()
