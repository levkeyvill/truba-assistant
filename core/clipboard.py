r"""Буфер обмена Windows: прочитать то, что хозяин скопировал.

Вторая пачка «рук» (`coordination/РУКИ_ПЛАН.md`): «прочитай, что я скопировал»
и «переведи скопированное». Отдельный маленький модуль, потому что больше
это читать нечем: `CF_UNICODETEXT` один, а WinAPI тут нужен ровно один раз.

Зависимостей нет — `ctypes` уже в проекте (`core/pc_control.py`,
`core/documents.py`), а ставить библиотеку ради одного вызова незачем.

Что важно в WinAPI, и почему так написано:

  * буфер обмена **общий на всю систему**, и пока его держит другая программа
    (Word, игра, файловый менеджер), `OpenClipboard` вернёт FALSE. Поэтому
    открываем с несколькими попытками и паузой (`ПОВТОРОВ`), а не один раз;
  * `GetClipboardData` отдаёт дескриптор блока памяти, а не сам текст: текст
    лежит под `GlobalLock`, и блок надо **обязательно** отпустить
    (`GlobalUnlock`), иначе память процесса-владельца останется запертой;
  * `CloseClipboard` — в `finally`, иначе после первого чтения буфер остался бы
    открытым до конца жизни процесса;
  * **всем вызовам объявлены `argtypes` и `restype`** (`_подписи`). Без
    объявленного `restype` `ctypes` считает возврат 32-битным `c_int`, и на
    64-битной Windows адрес блока памяти обрезался бы наполовину: `c_wchar_p`
    получил бы не тот адрес (или упал бы). Поэтому дескрипторы и адреса —
    только указательные типы (`HANDLE`/`HGLOBAL` = `c_void_p`); это тот же
    случай «подмена прятала ошибку», что в `coordination/ГРАБЛИ.md`;
  * **ничего не пишем в буфер**: `EmptyClipboard` и `SetClipboardData` здесь
    не встречаются вовсе, и это проверяется тестом.

Никакого исключения наружу: зовут голосовой инструмент и тесты, ответ — тот
же словарь, что у `core/documents.py`.
"""

import ctypes
import time

# `CF_UNICODETEXT` — единственный формат, который здесь нужен: текст в
# Unicode. Картинки и файлы из буфера (`CF_DIB`, `CF_HDROP`) хозяину читать
# нечего, и молча отдавать пустоту нельзя — это честный отказ.
CF_UNICODETEXT = 13

# Сколько знаков отдаём. Хозяин копирует в буфер абзац или страницу, а не
# книгу; больше 12 000 знаков (как у `core/documents.py::TEXT_LIMIT`) читать
# вслух бессмысленно — это несколько минут её голоса. Обрезанное помечаем
# честным `cut`, а не отдаём молча половину.
MAX_CHARS = 12000

# Сколько раз пробуем открыть буфер, пока он занят, и пауза между попытками.
# Буфер общий на всю систему: пока хозяин копирует, его держит та программа,
# из которой он копирует, — это доли секунды.
ПОВТОРОВ = 5
ПАУЗА = 0.02


def _user32():
    """Системная библиотека окон. Отдельной функцией — её подменяют тесты."""
    return ctypes.windll.user32


def _kernel32():
    """Системная библиотека памяти: ею берётся и отпускается блок буфера."""
    return ctypes.windll.kernel32


# Типы WinAPI объявлены явно, а не «как получится». `HANDLE` и `HGLOBAL` в
# Windows — это `void*`: на 64 битах 8 байт, на 32 — 4. Объявить возврат как
# `c_int` (а именно этим `ctypes` считает вызов без объявленного `restype`)
# значит отбросить верхние байты адреса, и `c_wchar_p` получит не тот адрес:
# на 64-битной машине это либо падение, либо чужое место в памяти. Именно
# на это наступил бы модуль, если бы подмена в тестах возвращала полный
# адрес в обход настоящего поведения `ctypes`.
BOOL = ctypes.c_int
HANDLE = ctypes.c_void_p
UINT = ctypes.c_uint


def _подписи(user32, kernel32) -> None:
    """Объявить `argtypes` и `restype` всем вызовам, что тут используются.

    Объявляем здесь, а не «где-то при инициализации»: подмена в тестах —
    обычные объекты с методами, и им есть куда положить сигнатуры, поэтому
    контракт типов проверяем по-настоящему. Живого буфера это не касается:
    трогаются только атрибуты функций, ни одного вызова WinAPI не делается.

    `GetClipboardData` и `GlobalLock` возвращают **адрес**, поэтому `restype`
    у них — `c_void_p` (`HANDLE`/`HGLOBAL`), а не `c_int`. Первым аргументом
    `GlobalLock`/`GlobalUnlock` идёт дескриптор — он тоже указательный.
    """
    user32.OpenClipboard.argtypes = (ctypes.c_void_p,)  # HWND окна
    user32.OpenClipboard.restype = BOOL
    user32.CloseClipboard.argtypes = ()
    user32.CloseClipboard.restype = BOOL
    user32.IsClipboardFormatAvailable.argtypes = (UINT,)
    user32.IsClipboardFormatAvailable.restype = BOOL
    # Возврат — дескриптор блока памяти, а не текст: 8 байт на 64 битах.
    user32.GetClipboardData.argtypes = (UINT,)
    user32.GetClipboardData.restype = HANDLE
    # Возврат — адрес внутри блока: тот самый, который обрезать нельзя.
    kernel32.GlobalLock.argtypes = (HANDLE,)
    kernel32.GlobalLock.restype = ctypes.c_void_p
    kernel32.GlobalUnlock.argtypes = (HANDLE,)
    kernel32.GlobalUnlock.restype = BOOL


def _открыть(user32, повторов: int = ПОВТОРОВ, пауза: float = ПАУЗА) -> bool:
    """Открыть буфер с повторами: он общий на всю систему.

    Одна неудача — ещё не «занят»: пока хозяин копирует, буфер держит та
    программа, из которой он копирует. Несколько попыток с паузой — и буфер
    откроется сам.
    """
    for номер in range(max(1, int(повторов))):
        try:
            if user32.OpenClipboard(None):
                return True
        except Exception:
            return False
        if номер + 1 < повторов:
            time.sleep(пауза)
    return False


def _отказ(why: str) -> dict:
    """Честный отказ: текста нет, но причина — есть."""
    return {"ok": False, "text": "", "chars": 0, "cut": False, "why": str(why)}


def _готово(text: str, chars: int, cut: bool) -> dict:
    return {"ok": True, "text": text, "chars": int(chars), "cut": bool(cut)}


def text(limit: int = MAX_CHARS) -> dict:
    """Текст буфера обмена. Ответ — тот же словарь, что у `core/documents.py`.

    `{"ok", "text", "chars" (знаков всего, до обрезки), "cut"}`, а при отказе
    — ещё `why` и пустой текст. Буфер при этом не меняется: мы только читаем
    и сразу отпускаем, что взяли.
    """
    try:
        user32 = _user32()
        kernel32 = _kernel32()
    except Exception as exc:
        return _отказ(f"буфер обмена недоступен: {type(exc).__name__}: {exc}")

    # Сигнатуры объявляем на настоящих вызовах перед первым обращением:
    # адрес блока памяти должен прийти целиком, а не обрезанным до 32 бит.
    _подписи(user32, kernel32)

    if not _открыть(user32):
        return _отказ("буфер обмена держит другая программа — скажи ещё раз")

    try:
        try:
            есть = user32.IsClipboardFormatAvailable(CF_UNICODETEXT)
        except Exception:
            есть = False
        if not есть:
            return _отказ("в буфере обмена нет текста — там картинка или файл")
        handle = user32.GetClipboardData(CF_UNICODETEXT)
        if not handle:
            return _отказ("в буфере обмена нет текста")
        адрес = kernel32.GlobalLock(handle)
        if not адрес:
            return _отказ("не смогла прочитать буфер обмена")
        try:
            # Блок памяти — это null-строка в UTF-16, а не строка Python:
            # `c_wchar_p` сам остановится на нуле, хвост мусора не попадёт.
            значение = ctypes.c_wchar_p(адрес).value or ""
        finally:
            # Блок отпускается в любом случае: запертая память чужого
            # процесса — это его полноценная утечка, а не мелочь.
            try:
                kernel32.GlobalUnlock(handle)
            except Exception:
                pass
    except Exception as exc:
        return _отказ(f"не прочитала буфер обмена: {type(exc).__name__}: {exc}")
    finally:
        # Буфер закрывается всегда — иначе следующее чтение его уже не откроет.
        try:
            user32.CloseClipboard()
        except Exception:
            pass

    # Переносы строк приходят из Windows как CRLF, а синтез и модель ждут
    # обычный перенос: без этого «хватит» посреди строки ломается.
    значение = значение.replace("\r\n", "\n").replace("\r", "\n").strip()
    if not значение:
        return _отказ("в буфере обмена пусто — читать нечего")

    всего = len(значение)
    обрезан = False
    if 0 < limit < всего:
        значение = значение[:limit].rstrip()
        обрезан = True
    return _готово(значение, всего, обрезан)


def journal_line(прочитан: dict) -> str:
    """Строка в журнал: «буфер обмена: 840 знаков». Без текста.

    Сам скопированный текст в журнал не уходит никогда: журнал хозяин читает
    сам и без телефона, а в буфере у него бывает всё, что он нашёл в сети.
    """
    знаков = int(прочитан.get("chars") or 0)
    from core.speech_text import plural

    куски = [f"буфер обмена: {знаков} "
             f"{plural(знаков, ('знак', 'знака', 'знаков'))}"]
    if прочитан.get("cut"):
        куски.append("только начало")
    return ", ".join(куски)
