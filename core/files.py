r"""Поиск файлов по названию и открытие через программу по умолчанию.

Поиск обходит папки в ширину без индекса и ограничен по времени.
Сначала проверяются стандартные папки: Рабочий стол, Документы, Загрузки,
Изображения, Видео, Музыка, папка заметок и хранилища
Obsidian, потом корни дисков. `drive` («C», «D») сужает поиск до одного диска и
его стандартных папок, если они на нём.

Служебные папки пропускаются: `Windows`,
`Program Files`, `AppData`, `node_modules`, `.git`, `.venv`, `venv`,
`__pycache__`, `.cache` и всё, что начинается с точки. Скрытое и системное — мимо,
ошибки доступа — молча мимо, по ссылкам (junction и symlink) не ходим: иначе
поиск зациклится и уйдёт в чужую папку.

Не успели за `SECONDS` — отдаём лучшее из найденного с признаком
`searched_all: False`.

Открытие — `os.startfile`, то есть программа по умолчанию. Исполняемые файлы и
скрипты не открываем: запуск по
названию файла — это запуск программ, а для них есть `launch_app` с белым
списком.

С тем же обходом ищутся и папки (`folders_only=True`): «открой на диске D папку
Torrent». Обход, пропуски и очки те же, кандидатом считается только каталог.

Если обычный круг ничего не нашёл, имена из того же обхода отбираются ещё раз,
уже нестрогими очками: распознавание речи коверкает названия, и «Torent» — это
«Torrent», а «торрент» — тоже «Torrent». Второго обхода диска не делается, имена
копились по ходу первого, а в ответе тогда стоит `approx: True`.

Ни одна функция здесь не бросает исключения: их зовёт инструмент модели, а
ошибка вместо ответа уронила бы разговор.
"""

import os
import re
import time
from collections import deque
from pathlib import Path

import config
from core import folders, personas

# Предел поиска: после него отдаём найденное и отмечаем незавершённый обход.
SECONDS = 6.0
# Число кандидатов ограничено, чтобы результат можно было уточнить голосом.
BEST = 5
# Слова короче трёх букв («по», «и», «за») в имя файла ничего не различают.
MIN_WORD = 3
# Двенадцати уровней хватает для обычных папок; предел дополняет ограничение времени.
MAX_DEPTH = 12

# Служебные папки исключены из поиска.
SKIP = frozenset({
    "windows", "program files", "program files (x86)", "programdata",
    "$recycle.bin", "system volume information", "appdata", "node_modules",
    ".git", ".venv", "venv", "__pycache__", ".cache",
})

# Расширения, которые не открываем никогда: это запуск программ, а не открытие
# документа. «Открыть по названию .exe» — ровно то, чем и пользуется вредоносный
# файл.
EXEC = frozenset({
    ".exe", ".bat", ".cmd", ".com", ".msi", ".ps1", ".vbs", ".vbe", ".js",
    ".jse", ".wsf", ".wsh", ".scr", ".pif", ".lnk", ".reg", ".hta", ".cpl",
    ".jar", ".py", ".pyw",
})

# Windows: атрибуты файла. Скрытое и системное мимо, `REPARSE` — это ссылка
# (junction или symlink), по ней не ходим.
HIDDEN = 0x2
SYSTEM = 0x4
REPARSE = 0x400

# Стандартные папки проверяются до корней дисков, в порядке `folders.KNOWN`.
STANDARD = ("desktop", "documents", "downloads", "pictures", "videos",
            "music", "notes")
def find(words: str, drive: str = "", limit_seconds: float = SECONDS,
         folders_only: bool = False) -> dict:
    """Файлы по словам названия. `{"ok", "found", "why", "searched_all"}`.

    `found` — до `BEST` лучших путей (`Path`), `searched_all` — False, если за
    `limit_seconds` обход не дошёл до конца. `why` — причина, когда ничего не
    нашлось или поиск не закончен; при успехе он пуст, кроме случая
    «не успела». `folders_only` — ищем папки, а не файлы: тем же обходом и с
    теми же очками, но кандидатом считается каталог.
    """
    искомые = _Запрос(_слова(words))
    искомые.слитно = _слитно(words)
    if not искомые:
        return {"ok": False, "found": [], "why": "не названо, что искать",
                "searched_all": True}

    начало = time.monotonic()
    найдено: dict = {}
    # Имена всех подходящих по виду записей — на случай нестрогого круга:
    # обход диска второй раз не повторяем, оцениваем собранное.
    кандидаты: list = []
    закончили = True
    встречено = 0
    корни = [Path(корень) for корень in _корни(drive)]
    # Корень диска может повторно привести в уже проверенные стандартные папки.
    пройдено = {_путь_ключ(корень) for корень in корни}
    очередь = deque((корень, 0) for корень in корни)
    while очередь:
        if time.monotonic() - начало > limit_seconds:
            закончили = False
            break
        папка, глубина = очередь.popleft()
        for entry in _содержимое(папка):
            if time.monotonic() - начало > limit_seconds:
                закончили = False
                очередь.clear()
                break
            встречено += 1
            if _собирать(entry, folders_only):
                _заметить(entry, искомые, найдено, встречено, folders_only,
                           True)
                if len(кандидаты) < APPROX_POOL:
                    кандидаты.append(entry)
            if not _заходить(entry) or глубина >= MAX_DEPTH:
                continue
            ключ = _путь_ключ(entry.path)
            if ключ in пройдено:
                continue
            пройдено.add(ключ)
            очередь.append((Path(entry.path), глубина + 1))

    лучшие = _лучшие(найдено)
    # Нестрогий круг включается только когда обычный не дал ничего: пока есть
    # точные совпадения, ложные «похожие» им не мешают.
    примерно = False
    if not лучшие:
        _отобрать_нестрого(кандидаты, искомые, найдено)
        лучшие = _лучшие(найдено)
        примерно = bool(лучшие)
    return {"ok": bool(лучшие), "found": лучшие,
            "why": _почему(искомые, лучшие, limit_seconds, закончили,
                           folders_only),
            "searched_all": закончили, "approx": примерно}


def open_file(path) -> dict:
    """Открыть файл или папку в программе по умолчанию. `{"ok", "text"}`.

    `os.startfile` открывает через программу по умолчанию. Исполняемое и
    скрипты — отказ: запуск по названию файла не наша работа.
    """
    цель = _путь(path)
    if цель is None:
        return {"ok": False, "text": "не поняла, какой файл открыть",
                "path": ""}
    имя = цель.name
    if not цель.exists():
        return {"ok": False, "text": f"файла «{имя}» больше нет",
                "path": str(цель)}
    if цель.is_dir():
        return _открыть_проводником(цель, имя)
    if цель.suffix.lower() in EXEC:
        return {"ok": False,
                "text": "запускать программы по названию файла не буду",
                "path": str(цель)}
    try:
        os.startfile(str(цель))
    except Exception as exc:
        return {"ok": False, "text": f"не открыла файл: {exc}",
                "path": str(цель)}
    return {"ok": True, "text": personas.say("file_open", config.PERSONA_PRESET,
                                               name=имя), "path": str(цель)}


def _открыть_проводником(цель: Path, имя: str) -> dict:
    """Папка — тот же `startfile`, что у `folders.open_folder`."""
    try:
        os.startfile(str(цель))
    except Exception as exc:
        return {"ok": False, "text": f"не открыла папку: {exc}",
                "path": str(цель)}
    return {"ok": True, "text": personas.say("folder", config.PERSONA_PRESET,
                                             name=f"«{имя}»"), "path": str(цель)}


def короткий(path) -> str:
    """Путь для модели: вместо `C:\\Users\\Имя\\` — `~\\`.

    В пути имя пользователя Windows, а модели оно ни к чему: только место в
    запросе и лишние слова о человеке, которого она не знает.
    """
    text = str(path or "")
    try:
        home = str(Path.home())
    except Exception:
        home = ""
    if home and text.lower().startswith(home.lower()):
        return "~" + text[len(home):]
    return text


def папка_пути(path) -> str:
    """Папка файла для ответа модели — тоже без имени пользователя."""
    цель = _путь(path)
    return короткий(цель.parent) if цель is not None else ""
# --- Где искать -------------------------------------------------------------


def _корни(drive: str) -> list:
    """Откуда идём: свои папки, хранилища Obsidian, потом корни дисков.

    `drive` — только этот диск и его стандартные папки, если они на нём.
    """
    from core import notes

    буква = str(drive or "").strip().upper()
    свои = []
    for folder_id in STANDARD:
        try:
            папка = folders.path_of(folder_id)
        except Exception:
            папка = None
        if папка is not None and (not буква or _на_диске(папка, буква)):
            свои.append(Path(папка))
    try:
        хранилища = notes._vaults()
    except Exception:
        хранилища = []
    for vault in хранилища:
        папка = _путь(vault)
        if папка is not None and (not буква or _на_диске(папка, буква)):
            свои.append(папка)
    for one in folders._drives():
        title = str(one.get("title", ""))
        if буква and title.rsplit(" ", 1)[-1].upper() != буква:
            continue
        корень = _путь(one.get("path"))
        if корень is not None:
            свои.append(корень)
    return свои


def _на_диске(путь, буква: str) -> bool:
    """Папка на этом диске — как у `Path.drive`, но безопасно."""
    try:
        return str(Path(путь).drive).rstrip(":\\").upper() == буква
    except Exception:
        return False


# --- Обход ------------------------------------------------------------------


def _содержимое(папка: Path) -> list:
    """Содержимое папки списком. Нет доступа — пусто, молча."""
    try:
        with os.scandir(str(папка)) as вещи:
            return list(вещи)
    except (OSError, ValueError):
        return []


def _свойства(entry) -> tuple:
    """`(это папка, атрибуты, время изменения)` для элемента каталога."""
    try:
        stat = entry.stat(follow_symlinks=False)
    except (OSError, ValueError):
        return False, 0, 0.0
    return (bool(_папка(entry)), int(getattr(stat, "st_file_attributes", 0) or 0),
            float(getattr(stat, "st_mtime", 0.0) or 0.0))


def _папка(entry) -> bool:
    """Элемент — папка (не по ссылке). Ошибка — False."""
    try:
        return bool(entry.is_dir(follow_symlinks=False))
    except (OSError, ValueError, AttributeError):
        return False


def _мимо(entry, папка: bool, атрибуты: int) -> bool:
    """Скрытое, системное или ссылка — мимо; служебная папка — тоже."""
    if атрибуты & (HIDDEN | SYSTEM | REPARSE):
        return True
    return bool(папка and _пропустить_папку(entry.name))


def _заходить(entry) -> bool:
    """Идти ли в этот элемент дальше: он папка и не мимо."""
    if not _папка(entry):
        return False
    return not _мимо(entry, True, _свойства(entry)[1])


def _пропустить_папку(имя: str) -> bool:
    """Системная папка, служебная или скрытая по имени."""
    name = str(имя or "").strip().lower()
    return (not name or name.startswith(".") or name in SKIP)


def _путь_ключ(путь) -> str:
    """Ключ папки для «уже пройдена», без учёта регистра и конечного слэша."""
    try:
        return os.path.normcase(os.path.normpath(str(путь)))
    except Exception:
        return str(путь)


def _собирать(entry, папки: bool) -> bool:
    """Запись годится в кандидаты: нужного вида, не скрытая, не ссылка.

    Те же пропуски, что и при обходе: служебную папку (`AppData`) и файл под
    системным атрибутом хозяину не показываем даже нестрогим кругом.
    """
    try:
        подходит = (entry.is_dir(follow_symlinks=False) if папки
                    else entry.is_file(follow_symlinks=False))
        if not подходит:
            return False
    except (OSError, ValueError, AttributeError):
        return False
    return not _мимо(entry, папки, _свойства(entry)[1])


def _заметить(entry, искомые: list, найдено: dict, порядок: int,
               папки: bool = False, подходит: bool | None = None) -> None:
    """Файл (или папка) подходит — запомнить его очки. Один и тот же — раз.

    При `папки` кандидатом считается каталог, и служебные имена (`SKIP`,
    точки) мимо, как при обходе: папку `AppData` хозяину не показывают.
    `подходит` — уже сделанная проверка `_собирать`: у элемента обхода она
    одна на оба круга, лишний `stat` на каждой записи не нужен.
    """
    if подходит is None:
        подходит = _собирать(entry, папки)
    if not подходит:
        return
    очки = _очки(entry.name, искомые)
    if not очки[0]:
        return
    ключ = _путь_ключ(entry.path)
    прежний = найдено.get(ключ)
    if прежний is not None and прежний[0] >= очки:
        return
    # `порядок` — номер находки: при равных очках и времени вперёд идёт тот, кого
    # обход встретил раньше, а свои папки обходятся раньше корня диска.
    найдено[ключ] = (очки, _свойства(entry)[2], порядок, str(entry.path))
# --- Совпадение -------------------------------------------------------------


def _слова(words: str) -> list:
    """Слова запроса от трёх букв: без регистра и `ё`, латиница как есть."""
    текст = re.sub(r"[^0-9a-zA-Zа-яё]+", " ",
                   str(words or "").lower().replace("ё", "е"))
    return [word for word in текст.split() if len(word) >= MIN_WORD]


def _слова_имени(имя: str) -> list:
    """Слова имени файла — те же буквы, что и в запросе."""
    return [word for word in re.sub(
        r"[^0-9a-zA-Zа-яё]+", " ", str(имя or "").lower().replace("ё", "е")
    ).split() if word]


class _Запрос(list):
    """Слова запроса плюс он же слитно — «higgstts3flashrt».

    Слитное сравнение помогает, когда короткие части и цифры выпадают из
    поиска по отдельным словам: «higgs tts 3» совпадает с «Higgs_TTS3».
    """

    слитно: str = ""


def _слитно(text: str) -> str:
    return re.sub(r"[^0-9a-zа-я]+", "", str(text or "").lower().replace("ё", "е"))


# Слитное совпадение считаем только от этой длины: «отчёт» слитно входит в
# «отчётность» — это уже работа обычных слов, а не склейки.
MIN_SLITNO = 8

# Нестрогий круг: имена копятся в первом обходе, а второй раз по диску мы не
# идём. Предел ограничивает память, а не время.
APPROX_POOL = 50000


def _отобрать_нестрого(кандидаты: list, искомые: list, найдено: dict) -> None:
    """Оценить собранные имена нестрогими очками, пока обычный круг пуст.

    Очки нестрогого круга меньше любых обычных: первый элемент — ноль, а у
    обычного круга он не меньше единицы, поэтому такие кандидаты не могли бы
    вытеснить точные совпадения, даже если бы попали в один словарь.
    """
    for порядок, entry in enumerate(кандидаты):
        очки = _очки_нестрого(entry.name, искомые)
        if not очки[0]:
            continue
        ключ = _путь_ключ(entry.path)
        прежний = найдено.get(ключ)
        if прежний is not None and прежний[0] >= очки:
            continue
        найдено[ключ] = ((0,) + очки, _свойства(entry)[2], порядок,
                         str(entry.path))


def _очки_нестрого(имя: str, искомые: list) -> tuple:
    """`(сколько слов нашлось, точное ли имя)` по нестрогому правилу.

    Без ведущего нуля: его ставит `_отобрать_нестрого`, чтобы такие очки
    всегда были ниже обычных.
    """
    слова = _слова_имени(имя)
    if not слова:
        return 0, 0
    слитно = getattr(искомые, "слитно", "")
    имя_слитно = _слитно(Path(str(имя)).stem)
    if слитно and слитно == имя_слитно:
        return len(искомые) + 1, 1
    запрос = list(искомые)
    найдены = {i for i, word in enumerate(запрос)
               if any(_слово_нестрого(одно, word) for одно in слова)}
    if not найдены:
        return 0, 0
    return len(найдены), int(_слова(Path(str(имя)).stem) == запрос)


def _слово_нестрого(одно: str, слово: str) -> bool:
    """«Torent» и «торрент» — это «torrent»: слова сравниваются нестрого.

    Обе стороны приводим к латинице одной таблицей, двойные буквы считаем за
    одну, и после этого слова либо равны, либо отличаются одной-двумя правками.
    """
    левое = _слово_простое(одно)
    правое = _слово_простое(слово)
    if not левое or not правое:
        return False
    if левое == правое:
        return True
    # Короткие слова нестрого не сравниваем: «стол» нашёл бы «стул».
    if min(len(левое), len(правое)) < APPROX_MIN:
        return False
    return _правки(левое, правое) <= _прощают(левое, правое)


def _слово_простое(слово: str) -> str:
    """Слово латиницей, без двойных букв и `ё`.

    Кириллица и латиница приводятся к одной таблице: сказанное по-русски
    «торрент» должно находить латинское «Torrent», и наоборот.
    """
    текст = str(слово or "").lower().replace("ё", "е")
    out = "".join(ЛАТИНИЦА.get(буква, буква) for буква in текст)
    return re.sub(r"(.)\1+", r"\1", out)


# Слова короче этой длины нестрогим кругом не сравниваются: правка в коротком
# слове меняет его смысл («стол» и «стул» — разные слова).
APPROX_MIN = 5
# Длинные слова терпят две правки вместо одной: «конспекты» и «конспект».
APPROX_LONG = 9


def _прощают(левое: str, правое: str) -> int:
    """Сколько правок в слове терпим: чем слово длиннее, тем больше."""
    return 2 if min(len(левое), len(правое)) >= APPROX_LONG else 1


def _правки(левое: str, правое: str) -> int:
    """Расстояние Левенштейна: вставка, удаление или замена буквы — одна правка."""
    if abs(len(левое) - len(правое)) > 2:
        return 3
    прежний = list(range(len(правое) + 1))
    for i, буква in enumerate(левое, 1):
        текущий = [i]
        for j, другая in enumerate(правое, 1):
            текущий.append(min(прежний[j] + 1, текущий[j - 1] + 1,
                               прежний[j - 1] + (буква != другая)))
        прежний = текущий
    return прежний[-1]


# Кириллица в латиницу: распознавание речи пишет русское слово кириллицей,
# а на диске оно латиницей.
ЛАТИНИЦА = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ж": "zh",
    "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n",
    "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f",
    "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "", "ы": "y",
    "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def _очки(имя: str, искомые: list) -> tuple:
    """`(сколько слов нашлось, точное ли имя)`. Ноль слов — не совпадение.

    Совпадение слова — по началу слова, падежный хвост терпим тем же
    правилом, что у папок (`folders._слово_подходит`): «отчёты» находит
    «отчёт», а «столовая» не считается «стол». Имя можно сказать без
    расширения: «отчёт» — это «отчёт.docx».
    """
    слова = _слова_имени(имя)
    if not слова:
        return 0, 0
    слитно = getattr(искомые, "слитно", "")
    имя_слитно = _слитно(Path(str(имя)).stem)
    if слитно and слитно == имя_слитно:
        # Имя целиком, как бы его ни разбили на слова: «план ремонта» — «Планремонта».
        return len(искомые) + 1, 1
    if len(слитно) >= MIN_SLITNO and слитно in имя_слитно:
        # Весь запрос целиком — сильнее любого частичного совпадения по словам.
        return len(искомые) + 1, 0
    запрос = list(искомые)
    найдены = {i for i, word in enumerate(запрос)
               if any(folders._слово_подходит(одно, word) for одно in слова)}
    # Сказано раздельно, а в имени слитно: «план ремонта» — «Планремонта.docx». Склейка
    # должна начинать слово имени целиком (падежный хвост терпим): правило
    # «по началу слова» тут не годится — «текстовыйфайл» начинается на «текст».
    for длина in (2, 3):
        for i in range(len(запрос) - длина + 1):
            клей = "".join(запрос[i:i + длина])
            if any(одно.startswith(клей) and len(одно) - len(клей) <= folders.TAIL
                   for одно in слова):
                найдены.update(range(i, i + длина))
    if not найдены:
        return 0, 0
    return len(найдены), int(_слова(Path(str(имя)).stem) == запрос)


def _лучшие(найдено: dict) -> list:
    """Лучшие совпадения: больше слов — точнее имя — свежее файл. До `BEST`.

    При равенстве и очков, и времени вперёд идёт тот, кого обход встретил раньше:
    свои стандартные папки обходятся раньше корня диска, и одинаковые файлы в
    них важнее лежащих в корне.
    """
    if not найдено:
        return []
    лучшие = max(очки for очки, _, _, _ in найдено.values())
    равные = [(когда, порядок, путь)
              for очки, когда, порядок, путь in найдено.values()
              if очки == лучшие]
    равные.sort(key=lambda one: (-one[0], one[1], one[2].lower()))
    return [Path(путь) for _, _, путь in равные[:BEST]]


def _почему(искомые: list, лучшие: list, предел: float, закончили: bool,
            папки: bool = False) -> str:
    """Честная причина: не нашла или не успела."""
    про_что = "папки про" if папки else "файла про"
    if закончили:
        return "" if лучшие else f"не нашла {про_что} «{' '.join(искомые)}»"
    не_успела = f"искала {_секунды(предел)}, дальше не успела"
    if лучшие:
        return не_успела
    return f"не нашла {про_что} «{' '.join(искомые)}» — {не_успела}"


def _секунды(предел: float) -> str:
    """«шесть секунд» — числами вслух не читаем, а словами."""
    from core.speech_text import cardinal

    try:
        return f"{cardinal(int(round(float(предел))))} секунд"
    except Exception:
        return f"{int(round(float(предел)))} секунд"


