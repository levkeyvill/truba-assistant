# К кому можно обращаться за компьютером. Короткий список: фраза должна быть
# про выключение целиком, а не упоминать его за компанию с чем-то ещё.
ОБЪЕКТ = r"(?:компьютер\w*|комп\w*|ноут\w*|машин\w*|пк|меня|нас)"

# Согласие. Одного «да» без названия действия недостаточно — это требование
# хозяина, а не перестраховка: «да» в разговоре значит тысячу чего.
СОГЛАСИЕ = (r"да|ага|угу|хорошо|ладно|ок|окей|подтвержда\w*|"
            r"согласен\w*|согласна|давай")

# Само действие словами. Окончание ловим явно, а не корнем: без этого
# «выключатель сломался» проходило бы как «выключить».
ВЫКЛЮЧЕНИЕ = (r"выключи|выключу|выключим|выключите|выключай|выключишь|"
              r"выключить|выключение|выключения|выключению|выключать|"
              r"выруби|вырубай|вырубить|вырублю|погаси|гаси")
ПЕРЕЗАГРУЗКА = (r"перезагрузи|перезагружу|перезагружай|перезагрузите|"
                r"перезагрузка|перезагрузки|перезагрузку|перезагружать|"
                r"перезапусти|перезапускай|перезапуск|ребутай|ребутни")
СОН = r"сон|сна|сном|спать|усып\w*|засып\w*"

# Подтверждение = согласие ИЛИ название действия, и обязательно само действие
# для ИМЕННО ТОГО, о чём шёл вопрос. Старое «подтверждаю сон», сказанное в
# ожидании выключения, сюда не попадает: у него нет слова про выключение.
ПОДТВЕРЖДЕНИЕ = {
    SHUTDOWN: re.compile(r"подтверждаю выключение|да выключай компьютер|"
                         r"да выключи компьютер|выключай компьютер"),
    RESTART: re.compile(r"подтверждаю перезагрузку|да перезагружай компьютер|"
                        r"перезагружай компьютер"),
    SLEEP: re.compile(r"подтверждаю сон|да усыпляй компьютер|"
                      r"усыпляй компьютер|отправляй компьютер в сон"),
}

# Отмена. Проверяется ПЕРВОЙ: «не выключай» — это отмена, а не согласие, и
# разбирать его подтверждением было бы ошибкой наизнанку.
ОТМЕНА = tuple(re.compile(узор) for узор in (
    r"отмен\w*",
    r"отмена\s+(?:выключения|перезагрузки|сна|сна компьютера)",
    r"не\s+надо",
    r"не\s+нужно",
    r"не\s+стоит",
    rf"не\s+надо\s+(?:{ВЫКЛЮЧЕНИЕ}|{ПЕРЕЗАГРУЗКА}|{СОН})\s*{ОБЪЕКТ}?",
    rf"не\s+(?:{ВЫКЛЮЧЕНИЕ})\s*{ОБЪЕКТ}?",
    rf"не\s+(?:{ПЕРЕЗАГРУЗКА})\s*{ОБЪЕКТ}?",
    rf"не\s+(?:{СОН})\s*{ОБЪЕКТ}?",
    r"стоп",
    r"хватит",
    r"забудь|забей",
    r"оставь",
    r"передумал|передумаю",
    r"ничего",
))

# Отмена уже идущего отсчёта. Название действия здесь не сверяется с тем,
# которое выполняется: `shutdown /a` отменяет любую отсрочку, а хозяин в
# спешке скажет «отмена выключения» и во время перезагрузки. Отличать надо
# только само намерение отменить — от «а что ты там хотела?», которое отменой
# не является.
ОТМЕНА_ОТСЧЁТА = ОТМЕНА + tuple(re.compile(узор) for узор in (
    r"отмен\w+\s+выключени\w*",
    r"отмен\w+\s+перезагруз\w*",
    r"отмен\w+\s+сон\w*",
    r"отмен\w+\s+сна",
    r"отмен\w+\s+засыпани\w*",
    r"отмен\w+\s+пробуждени\w*",
))

# Что сказать вслух. Вопрос в `ask`, результат в `execute` — по одному на
# действие, чтобы в журнал и в пульт ушло то же, что услышал хозяин.
ВОПРОС = {
    SHUTDOWN: ("Точно выключить компьютер? Windows через минуту закроет программы; "
               "несохранённое может пропасть. Для подтверждения скажи слово "
               "«подтверждаю» и назови действие. Для отказа скажи «отмена»."),
    RESTART: ("Точно перезагрузить компьютер? Windows через минуту закроет программы; "
              "несохранённое может пропасть. Для подтверждения скажи слово "
              "«подтверждаю» и назови действие. Для отказа скажи «отмена»."),
    SLEEP: ("Точно отправить компьютер в сон? Для подтверждения скажи слово "
            "«подтверждаю» и назови действие. Для отказа скажи «отмена». "
            "Сон отменить голосом нельзя: разбудить придётся "
            "кнопкой питания."),
}
СДЕЛАНО = {
    SHUTDOWN: ("Выключаю компьютер через минуту. Скажешь «отмена "
               "выключения» — отменю."),
    RESTART: ("Перезагружаю компьютер через минуту. Скажешь «отмена "
              "перезагрузки» — отменю."),
    SLEEP: "Отправляю компьютер в сон. Разбудить голосом уже не выйдет — "
           "только кнопкой питания.",
}
ОТМЕНЕНО = {
    SHUTDOWN: "Хорошо, компьютер оставляю включённым.",
    RESTART: "Хорошо, не перезагружаю.",
    SLEEP: "Хорошо, оставляю компьютер включённым.",
}
# Журнал: без командной строки, хозяин читает сам.
ИМЯ = {SHUTDOWN: "выключение", RESTART: "перезагрузка", SLEEP: "сон"}


def _голое(текст: str) -> str:
    """Фраза до слов: нижний регистр, без ё, без знаков. Как в commands."""
    lowered = (текст or "").lower().replace("ё", "е")
    return re.sub(r"\s+", " ", re.sub(r"[^а-яa-z0-9]+", " ", lowered)).strip()


def _подходит(фраза: str, узоры) -> bool:
    """Совпала ли фраза с одним из узоров **целиком**.

    Именно целиком: «да, выключай компьютер, а то я спать иду» — это не
    подтверждение, а разговор, и подтверждать по нему нельзя. Плюс при
    пустой фразе (распознавание не узнало ни слова) — тоже false: тишина
    ничего не подтверждает.
    """
    готово = _голое(фраза)
    if not готово:
        return False
    return any(узор.fullmatch(готово) for узор in узоры)



# --- Ожидание ---------------------------------------------------------------
#
# Два состояния, оба в памяти процесса и под одним замком:
#   `_ждём`    — задали вопрос, ждём подтверждения (не дольше WAIT секунд);
#   `_считает` — команда принята системой, идёт минута до отключения.
#
# На диск это не пишется намеренно. Файл «хозяин просил выключиться» пережил бы
# перезапуск пульта, и в следующий раз компьютер выключился бы сам.

_lock = threading.Lock()
_ждём: dict = {}
_считает: dict = {}
_runtime_live = False


def live_runtime() -> bool:
    """Системные вызовы разрешены только процессу настоящего пульта."""
    with _lock:
        return _runtime_live


def enable_live_runtime() -> None:
    """Вызывает точка входа пульта; тесты и копия Cline остаются без питания."""
    global _runtime_live
    if Path(sys.argv[0]).name.lower() != "window.py":
        return
    if Path(__file__).resolve().parents[1].name.lower().endswith("_cline"):
        return
    with _lock:
        _runtime_live = True


def disable_live_runtime() -> None:
    global _runtime_live
    with _lock:
        _runtime_live = False
        _ждём.clear()


def reset() -> None:
    """Сбросить оба состояния. Им пользуются тесты, а не голосовой цикл."""
    global _runtime_live
    with _lock:
        _ждём.clear()
        _считает.clear()
        _runtime_live = False


def _сейчас(now=None) -> float:
    return time.monotonic() if now is None else float(now)


def pending(now=None) -> str | None:
    """Какое действие ждёт подтверждения. None — не ждёт или уже сгорело."""
    now = _сейчас(now)
    with _lock:
        if not _ждём:
            return None
        if now - float(_ждём.get("since", 0.0)) > WAIT:
            # Вопрос сгорел: забытое «выключи компьютер» не должно проснуться
            # через час на его «ну да».
            _ждём.clear()
            return None
        return str(_ждём.get("action") or "") or None


def counting(now=None) -> str | None:
    """Идёт ли отсчёт до отключения. None — не идёт (или уже отключился)."""
    now = _сейчас(now)
    with _lock:
        if not _считает:
            return None
        if now >= float(_считает.get("until", 0.0)):
            _считает.clear()
            return None
        return str(_считает.get("action") or "") or None


def ask(action: str, now=None) -> dict:
    """Просьба безопасно готовит действие и спрашивает. Систему не трогает.

    Вызова `backend()` здесь быть не может — и это проверяется тестом, а не
    обещанием: тест подменяет backend на запись и требует пустого журнала.
    """
    действие = str(action or "").strip().lower()
    if действие not in ACTIONS:
        return {"ok": False, "action": действие, "text": "",
                "journal": f"питание: не поняла действие «{действие or 'пусто'}»",
                "event": "power_failed"}
    with _lock:
        _ждём.clear()
        _ждём.update(action=действие, since=_сейчас(now))
    return {
        "ok": True,
        "action": действие,
        "text": ВОПРОС[действие],
        "journal": f"питание: жду подтверждения — {ИМЯ[действие]}",
        "event": "power_asked",
    }


def answer(текст: str, now=None) -> dict:
    """Второй голосовой ход. Возвращает `verdict`:

      * `none`   — подтверждения не ждали (жди не было или оно сгорело);
      * `other`  — ждали, но это не подтверждение: ожидание сброшено, фраза
                    идёт обычным путём — к командам и к модели;
      * `cancel` — хозяин передумал;
      * `confirm`— назвал именно это действие, и оно выполнено (или честно не
                    получилось, см. `ok`).

    Действие выполняется **только** при `confirm`. Слова модели сюда не приходят
    вообще: разбор стоит в голосовом цикле до вызова модели, и инструмент
    модели (`core/hands.py`) тоже умеет только `ask`, но не `execute`.
    """
    now = _сейчас(now)
    with _lock:
        действие = str(_ждём.get("action") or "")
        if действие and now - float(_ждём.get("since", 0.0)) > WAIT:
            действие = ""
        # Только один поток может забрать подтверждение. Второй увидит пусто.
        _ждём.clear()
    if not действие:
        return {"verdict": "none", "action": "", "ok": False, "text": "",
                "journal": "", "event": ""}
    if _подходит(текст, ОТМЕНА):
        return {"verdict": "cancel", "action": действие, "ok": False,
                "text": ОТМЕНЕНО[действие],
                "journal": f"питание: {ИМЯ[действие]} — хозяин отменил",
                "event": "power_cancelled"}
    if not _подходит(текст, [ПОДТВЕРЖДЕНИЕ[действие]]):
        # Одинокое «да», шум, похожие слова и подтверждение для ДРУГОГО
        # действия: не делаем ничего. Молчание тут честнее отказа вслух —
        # хозяин скажет, что хотел, и спросим заново.
        return {"verdict": "other", "action": действие, "ok": False, "text": "",
                "journal": "", "event": ""}
    return {"verdict": "confirm", **execute(действие, now=now, _token=_CONFIRM_TOKEN)}


def abort_requested(текст: str, now=None) -> bool:
    """Просил ли хозяин отменить уже идущий отсчёт («отмена выключения»)."""
    return counting(now) is not None and _подходит(текст, ОТМЕНА_ОТСЧЁТА)


def abort(now=None) -> dict:
    """Отмена отсчёта: `shutdown /a`. Голосом, во время минуты."""
    with _lock:
        было = str(_считает.get("action") or "")
    if not было:
        return {"ok": False, "action": "", "text": "Ничего отменять нечего.",
                "journal": "питание: отменять нечего",
                "event": "power_abort_failed"}
    try:
        итог = backend().abort()
    except Exception as exc:
        итог = {"ok": False, "why": f"{type(exc).__name__}: {exc}"}
    if not итог.get("ok"):
        return {"ok": False, "action": было,
                "text": "Не вышло отменить. Выключение всё ещё запланировано; сохрани работу.",
                "journal": f"питание: отмена {ИМЯ.get(было, было)} не вышла: "
                           f"{итог.get('why') or 'система молчит'}",
                "event": "power_abort_failed"}
    with _lock:
        _считает.clear()
    return {"ok": True, "action": было,
            "text": f"Отменила {ИМЯ.get(было, было)}, компьютер останется "
                    f"включённым.",
            "journal": f"питание: {ИМЯ.get(было, было)} — отмена принята системой",
            "event": "power_abort"}


_CONFIRM_TOKEN = object()


def execute(действие: str, now=None, _token=None) -> dict:
    """Выполнить через backend. Зовётся только из `answer`, по точному слову."""
    now = _сейчас(now)
    имя = str(действие or "").strip().lower()
    if имя not in ACTIONS:
        return {"action": имя, "ok": False, "text": "Не поняла, что сделать.",
                "journal": "питание: неизвестное действие",
                "event": "power_failed"}
    if _token is not _CONFIRM_TOKEN:
        return {"action": имя, "ok": False,
                "text": "Нет голосового подтверждения. Попроси ещё раз.",
                "journal": "питание: действие отклонено без голосового подтверждения",
                "event": "power_failed"}
    try:
        if имя == SLEEP:
            итог = backend().sleep()
        else:
            итог = getattr(backend(), имя)(COUNTDOWN)
    except Exception as exc:
        итог = {"ok": False, "why": f"{type(exc).__name__}: {exc}"}
    if not итог.get("ok"):
        # Честный отказ: система не приняла команду — компьютер остаётся
        # включённым, и сказать «выключаю» было бы враньём.
        return {"action": имя, "ok": False,
                "text": "Не получилось: система не приняла команду. "
                        "Компьютер остаётся включённым.",
                "journal": f"питание: {ИМЯ[имя]} не вышло — "
                           f"{итог.get('why') or 'система молчит'}",
                "event": "power_failed"}
    if имя != SLEEP:
        # Отсчёт пошёл: помним на минуту, чтобы «отмена выключения» знала,
        # что отменять. Сном это не нужно — его голосом не отменяют.
        with _lock:
            _считает.update(action=имя, until=now + COUNTDOWN)
        строка = (f"питание: {ИМЯ[имя]} принято системой, отсчёт "
                  f"{COUNTDOWN} с")
    else:
        строка = f"питание: {ИМЯ[имя]} принято системой"
    return {"action": имя, "ok": True, "text": СДЕЛАНО[имя],
            "journal": строка, "event": "power_done"}
