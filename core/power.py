r"""Питание компьютера голосом: выключение, перезагрузка, сон.

Вторая пачка «рук» (`coordination/РУКИ_ПЛАН.md`): «выключи компьютер»,
«перезагрузи», «отправь в сон». Правило хозяина одно и не шуточное:
**необратимое — только с переспросом**. Поэтому здесь устроено так:

  * просьба только **готовит** действие и спрашивает вслух. Ни одного вызова
    системы на первом шаге нет вообще — это проверяется тестом;
  * второй голосовой ход разбирается **здесь, локально и до вызова модели**
    (`answer`): подтверждение должно назвать действие. «да» без названия,
    «угу», подтверждение для ДРУГОГО действия и слова, прочитанные из
    документа, не подтверждают ничего;
  * ожидание живёт в памяти процесса (`_ждём`) и **не пишется на диск**: файл
    с отметкой «хозяин попросил выключиться» пережил бы перезапуск и был бы
    готов сработать без спроса;
  * ждать не дольше `WAIT` секунд: забытый вопрос о выключении через полчаса
    опаснее лишнего «а что?».

Само питание — тремя вызовами Windows:

  * `shutdown /s /t 60` и `shutdown /r /t 60` — минута на отмену, и голосом
    «отмена выключения» (`shutdown /a`) прямо во время отсчёта;
  * `SetSuspendState` — сон. Отменить его голосом уже нельзя: компьютер
    уснул, микрофона нет. Поэтому в вопросе про сон это сказано заранее.

Всё это живёт за `backend()` — единственным местом, где модуль касается
системы. Тесты подменяют backend целиком, и ни один настоящий вызов из тестов
не доходит до Windows: ни `shutdown`, ни `SetSuspendState`, ни `shutdown /a`.
"""

import ctypes
import re
import subprocess
import sys
import threading
import time
from pathlib import Path

# Что умеем. Порядок значим: он в `enum` инструмента и в вопросе вслух.
ACTIONS = ("shutdown", "restart", "sleep")
SHUTDOWN, RESTART, SLEEP = ACTIONS

# Минута до отключения: `/t 60`. Не меньше — хозяину нужно успеть добежать и
# сказать «отмена», иначе переспрос теряет смысл. Не больше — «минута на
# отмену» это его время, а не наше.
COUNTDOWN = 60

# Сколько ждём подтверждения голосом. Ровно 30 секунд: он ответит сразу, а если
# отошёл от микрофона — вопрос сгорает сам, и через полчаса «да» не выключит
# компьютер, которого он уже не помнит.
WAIT = 30.0


# --- Система ----------------------------------------------------------------


def _без_окна() -> int:
    """Флаг «не показывать окно консоли». На живой машине есть всегда."""
    return getattr(subprocess, "CREATE_NO_WINDOW", 0)


def _хвост(итог) -> str:
    """Что Windows ответила на команду. В отказе это и есть причина."""
    parts = [str(getattr(итог, "stdout", "") or ""),
             str(getattr(итог, "stderr", "") or "")]
    текст = " ".join(part.strip() for part in parts if part.strip())
    return текст[:160]


class Windows:
    """Настоящие системные вызовы. Отдельный класс — чтобы подменить.

    Ответ везде один и тот же: `{"ok": bool, "why": str, "args": list}`.
    `why` при `ok` пуст, при отказе — причина: «честный отказ, никакого
    „выключаю“, если команда не принята» (см. `execute`).
    """

    def _run(self, args: list, *, cancelling: bool = False) -> dict:
        if not live_runtime() or (cancelling and not counting()):
            return {"ok": False, "why": "системное питание доступно только из запущенного пульта", "args": list(args)}
        try:
            итог = subprocess.run(
                list(args), capture_output=True, text=True, timeout=15,
                creationflags=_без_окна(),
            )
        except Exception as exc:
            # Намеренно Exception, а не пара подкласса: сюда попадает и
            # FileNotFoundError, если система не нашлась, и TimeoutExpired.
            # Наружу отказ должен уйти текстом, а не исключением — зовут и
            # голосовой цикл, и инструмент модели.
            return {"ok": False, "why": f"{type(exc).__name__}: {exc}",
                    "args": list(args)}
        if int(getattr(итог, "returncode", 1) or 0) != 0:
            return {"ok": False,
                    "why": _хвост(итог) or f"код {итог.returncode}",
                    "args": list(args)}
        return {"ok": True, "why": "", "args": list(args)}

    def shutdown(self, seconds: int = COUNTDOWN) -> dict:
        return self._run(["shutdown", "/s", "/t", str(int(seconds))])

    def restart(self, seconds: int = COUNTDOWN) -> dict:
        return self._run(["shutdown", "/r", "/t", str(int(seconds))])

    def abort(self) -> dict:
        # `/a` отменяет любую уже запущенную отсрочку: и выключение, и
        # перезагрузку. Время отсчёта тут не задаётся.
        return self._run(["shutdown", "/a"], cancelling=True)

    def sleep(self) -> dict:
        if not live_runtime():
            return {"ok": False, "why": "системное питание доступно только из запущенного пульта", "args": ["SetSuspendState"]}
        try:
            вызов = ctypes.windll.powrprof.SetSuspendState
            # Без объявленных типов `ctypes` считает возврат 32-битным, а
            # здесь нужен честный BOOL (ГРАБЛИ, про `restype`).
            вызов.argtypes = [ctypes.c_ubyte, ctypes.c_ubyte, ctypes.c_ubyte]
            вызов.restype = ctypes.c_ubyte
            # False — это сон, а не гибернация: гибернация у хозяина
            # выключена, и компьютер с неё сам не просыпается.
            результат = int(вызов(False, False, False) or 0)
        except Exception as exc:
            return {"ok": False, "why": f"{type(exc).__name__}: {exc}",
                    "args": ["SetSuspendState"]}
        if not результат:
            return {"ok": False, "why": "Windows отказала в засыпании",
                    "args": ["SetSuspendState"]}
        return {"ok": True, "why": "", "args": ["SetSuspendState"]}


_BACKEND = Windows()


def backend():
    """Тот самый backend. Тесты подменяют его целиком — и больше ничего."""
    return _BACKEND


