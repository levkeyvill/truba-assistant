# Разряды: множитель, род, три формы для счёта.
SCALES = (
    (10 ** 12, "m", ("триллион", "триллиона", "триллионов")),
    (10 ** 9, "m", ("миллиард", "миллиарда", "миллиардов")),
    (10 ** 6, "m", ("миллион", "миллиона", "миллионов")),
    (10 ** 3, "f", ("тысяча", "тысячи", "тысяч")),
)
FRACTIONS = (
    ("десятая", "десятых"), ("сотая", "сотых"), ("тысячная", "тысячных"),
    ("десятитысячная", "десятитысячных"),
)


def plural(n: int, forms: tuple[str, str, str]) -> str:
    """Выбирает форму слова под число: 1 рубль, 2 рубля, 5 рублей."""
    n = abs(n) % 100
    if 11 <= n <= 14:
        return forms[2]
    last = n % 10
    if last == 1:
        return forms[0]
    if 2 <= last <= 4:
        return forms[1]
    return forms[2]


def _by_digits(n: int) -> str:
    """Читает число по цифрам — для того, что в разряды не укладывается."""
    return " ".join("ноль" if d == "0" else ONES["m"][int(d)] for d in str(n))


def _under_thousand(n: int, gender: str) -> list[str]:
    words = []
    if n >= 100:
        words.append(HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        words.append(TEENS[n - 10])
        return words
    if n >= 20:
        words.append(TENS[n // 10])
        n %= 10
    if n:
        words.append(ONES[gender][n])
    return words


BIGGEST = 10 ** 15


def cardinal(n: int, gender: str = "m") -> str:
    """Число словами: 240 → «двести сорок», 21 (ж) → «двадцать одна»."""
    if n == 0:
        return "ноль"

    words = []
    if n < 0:
        words.append("минус")
        n = -n

    # Больше триллионов в разрядах нет, да и вслух такое читают по цифрам:
    # номер карты, счёт, длинный идентификатор.
    if n >= BIGGEST:
        return " ".join(words + [_by_digits(n)])

    for scale, scale_gender, forms in SCALES:
        if n < scale:
            continue
        count, n = divmod(n, scale)
        words += _under_thousand(count, scale_gender)
        words.append(plural(count, forms))

    if n:
        words += _under_thousand(n, gender)

    return " ".join(w for w in words if w)


def _decimal(whole: str, frac: str, gender: str = "m") -> str:
    """Дробь словами: 3.5 → «три целых пять десятых»."""
    frac = frac.rstrip("0") or "0"
    if len(frac) > len(FRACTIONS):
        # Длиннее тысячных в разговоре не встречается — читаем по цифрам.
        digits = " ".join(cardinal(int(d)) for d in frac)
        return f"{cardinal(int(whole), gender)} и {digits}"

    value = int(frac)
    one, many = FRACTIONS[len(frac) - 1]
    whole_n = int(whole)
    return (
        f"{cardinal(whole_n, 'f')} "
        f"{plural(whole_n, ('целая', 'целых', 'целых'))} "
        f"{cardinal(value, 'f')} {plural(value, (one, many, many))}"
    )


