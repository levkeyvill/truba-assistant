r"""Подготовка текста к синтезу: цифры и латиница — словами.

Silero русская и читает только кириллицу. Замерено 21 сентября 2026:

    «Возьми SSD на 240 Гб.»   звучит 0.94 с вместо 2.70 — то есть «Возьми на»
    «Сейчас 18:42.»           звучит 0.70 с вместо 1.95 — то есть «Сейчас»
    «CPU и GPU»               звучит 0.31 с — только союз «и»
    «240», «SSD», «Hello»     синтез падает с ValueError, реплика пропадает

То есть всё, что не кириллица, она молча выбрасывает, а если выбрасывать
больше нечего — валится. Поэтому текст переводится здесь: числа в слова
с падежом и родом, латиница по словарю, незнакомое — по буквам.

Наружу нужны две вещи:

    for_speech(text)  — текст, пригодный для синтеза
    speakable(text)   — осталось ли в нём что произносить
"""

