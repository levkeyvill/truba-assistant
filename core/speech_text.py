def _latin_word(word: str) -> str:
    """Латинское слово по-русски."""
    known = WORDS.get(word.lower())
    if known:
        return known

    # Аббревиатура — читаем по буквам: SSD, HDMI, RTX.
    if word.isupper() and len(word) <= 5:
        return " ".join(LETTERS.get(ch, ch) for ch in word.lower())

    out = word.lower()
    for source, target in TRANSLIT:
        out = out.replace(source, target)
    return out


# --- Сборка --------------------------------------------------------------

CYRILLIC = re.compile(r"[а-яёА-ЯЁ]")


def for_speech(text: str, keep_latin: bool = False) -> str:
    """Переписывает текст так, как его надо прочитать вслух.

    keep_latin — оставить латиницу как есть: многоязычная модель (Higgs)
    читает английские слова сама и лучше нашего транслита.
    """
    if not text:
        return ""

    out = text

    # Служебные значки, которые в речи не произносятся или мешают.
    out = out.replace("&", " и ").replace("№", " номер ")
    out = re.sub(r"[*_`#|]+", " ", out)
    # Знаки действий между числами: «2 + 2 = 4».
    out = re.sub(r"(?<=\d)\s*\+\s*(?=\d)", " плюс ", out)
    out = re.sub(r"(?<=\d)\s*=\s*(?=\d)", " равно ", out)
    # Минус перед числом, но не дефис внутри слова и не тире диапазона.
    out = re.sub(r"(?:(?<=^)|(?<=[\s(]))[-−](?=\d)", "минус ", out)
    # Длинные числа пишут с разделителями: 1 000 000, 12,345.
    out = re.sub(r"(?<=\d)[  ](?=\d{3}\b)", "", out)

    # Время: 18:42 → «восемнадцать сорок две». Минуты женского рода.
    def _time(m):
        hours, minutes = int(m.group(1)), int(m.group(2))
        if minutes == 0:
            return f"{cardinal(hours)} {plural(hours, ('час', 'часа', 'часов'))} ровно"
        return f"{cardinal(hours)} {cardinal(minutes, 'f')}"

    out = re.sub(r"\b([01]?\d|2[0-3]):([0-5]\d)\b", _time, out)

    # Скорость: 896 GB/s → «гигабайт в секунду».
    out = re.sub(r"(?<=[A-Za-zА-Яа-яё])\s*/\s*(?:s|с)\b", " в секунду", out)

    # Дата: 21 сентября → «двадцать первого сентября».
    out = re.sub(
        rf"\b(\d{{1,2}})\s+({MONTHS_GENITIVE})\b",
        lambda m: f"{_ordinal_word(int(m.group(1)), 'го') or m.group(1)} {m.group(2)}",
        out,
    )
    # Год: 2026 года → «две тысячи двадцать шестого года».
    out = re.sub(
        r"\b(\d{4})\s+(год[ауе]?|году|года)\b",
        lambda m: f"{_ordinal_word(int(m.group(1)), 'го') or m.group(1)} {m.group(2)}",
        out,
    )

    # Число с единицей: 240 Гб, 8 ГБ, 100 ₽, 50%, 2.5 кг.
    def _measure(m):
        whole, frac, unit = m.group(1), m.group(2), m.group(3)
        gender, forms = UNITS[unit.lower()]
        if frac:
            # При дроби существительное идёт в родительном: «девять целых
            # тридцать одна сотая гигабайта».
            return f"{_decimal(whole, frac, gender)} {forms[1]}"
        value = int(whole)
        return f"{cardinal(value, gender)} {plural(value, forms)}"

    out = re.sub(
        rf"\b(\d+)(?:[.,](\d+))?\s*({UNIT_RE})(?![а-яёa-z])"
        # «за 2 с половиной» — это не секунды, а предлог. Не трогаем.
        r"(?!\s*(?:половиной|лишним|чем|хвостиком|копейками))",
        _measure,
        out,
        flags=re.IGNORECASE,
    )

    # Порядковые с дефисом: 5-й, 2-го, 3-е.
    out = re.sub(
        r"\b(\d+)-(го|му|ми|й|м|е|я|ю|х)\b",
        lambda m: _ordinal_word(int(m.group(1)), m.group(2)) or m.group(0),
        out,
    )

    # Дробные и целые числа сами по себе.
    out = re.sub(
        r"\b(\d+)[.,](\d+)\b", lambda m: _decimal(m.group(1), m.group(2)), out
    )

    subject = out

    def _plain_number(m):
        # Род берём у следующего слова: «одна минута», но «один час».
        after = subject[m.end():].lstrip()
        gender = "f" if FEMININE_NEXT.match(after) else "m"
        return cardinal(int(m.group(0)), gender)

    out = re.sub(r"\d+", _plain_number, subject)

    # Латиница — последней: до неё в тексте могли быть GB и Ti.
    if not keep_latin:
        out = re.sub(r"[A-Za-z]+", lambda m: _latin_word(m.group(0)), out)

    return re.sub(r"[ \t]{2,}", " ", out).strip()


