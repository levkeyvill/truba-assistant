# Женский род у числа виден только по следующему слову: «одна минута»,
# но «один час». Здесь корни тех слов, что реально встречаются в её речи.
FEMININE_NEXT = re.compile(
    r"^(?:минут|секунд|тысяч|штук|копей|недел|тонн|сотн|пар|игр|карт|строк|"
    r"ошибк|задач|программ|кнопк|папк|верси|попытк|команд|модел|видюх|"
    r"вкладк|стран|фраз|реплик|запис|проверк)",
    re.IGNORECASE,
)


def _ordinal_word(value: int, ending: str) -> str | None:
    """«5-го» → «пятого». None — если такое число не осилили."""
    words = cardinal(value).split()
    nominative = ORDINALS.get(words[-1])
    if nominative is None:
        return None
    cases = ORDINAL_CASES.get(ending)
    if cases is None:
        return None
    words[-1] = nominative[:-2] + cases[nominative[-2:]]
    return " ".join(words)


def speakable(text: str) -> bool:
    """Есть ли в тексте хоть что-то, что Silero сможет произнести.

    Без этой проверки кусок без кириллицы роняет синтез, и реплика
    пропадает целиком — молча, человек просто не дожидается ответа.
    """
    return bool(CYRILLIC.search(text or ""))
