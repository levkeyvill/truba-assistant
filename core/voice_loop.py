# принятая фраза копится в буфер. Разбор команд и облако в это время
# пропускаются — иначе «всё» ушло бы в модель, а середина мысли —
# поговорить с ней вместо записи.
#
# Диктовка кончается тремя способами: фразой («всё», «записывай»,
# «конец заметки», «хватит»), отменой («отмена», «не записывай») или
# тишиной в DICTATION_PAUSE секунд. Тишину ловит сторож: пока он молчит,
# думая над фразой, ждать надо, а замолчал — значит закончил.

DICTATION_END = re.compile(
    r"^\s*(?:вс[её]|записывай|записывайте|конец заметки|хватит|пора|"
    r"закончил|готово)\s*[.!]*\s*$",
    re.IGNORECASE,
)
# Хвост в конце фразы: «вот про это и всё», «мысль такая, всё». Саму
# фразу надо досочистить до буфера, а «всё» — не часть мысли.
# Голое «все» в конце сюда не входит: «…как и все» — обычный конец мысли,
# и запись оборвалась бы посреди диктовки. Одно «всё» отдельной фразой
# ловит DICTATION_END.
DICTATION_TAIL = re.compile(
    r"[,\s]*(?:(?:вс[её][,\s]+)?записывай(?:те)?|конец заметки)\s*[.!]*\s*$",
    re.IGNORECASE,
)
DICTATION_CANCEL = re.compile(
    r"^\s*(?:отмена|отмени|не записывай|не записывать|отставить|забудь)\s*[.!]*\s*$",
    re.IGNORECASE,
)
# Что говорим в начале и в конце. Короткое: во время диктовки она молчит.
DICTATION_START = "Диктуй. Скажешь «всё» — запишу."
DICTATION_EMPTY = "Нечего записывать."
DICTATION_CANCEL_SAY = "Не записываю."
DICTATION_DONE = "Готово, записала."


