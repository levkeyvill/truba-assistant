def _trouble_words(exc: Exception) -> str:
    """Что сказать вслух, если модель не ответила."""
    text = f"{type(exc).__name__} {exc}".lower()
    if "country" in text or "region" in text:
        # Про VPN — не «отвалился»: у многих его нет вовсе, и отказ по стране
        # для них значит «нужен VPN или другой сервис».
        return "Облако меня не пускает из этой страны — нужен VPN или другой сервис."
    if "connection" in text or "timeout" in text or "timed out" in text:
        return "Не могу достучаться до облака, проверь интернет."
    if "insufficient" in text or "quota" in text or "balance" in text:
        return "В облаке кончились деньги на счёте."
    return "Что-то сломалось в облаке, ответить не могу."


def _is_network_error(exc: Exception) -> bool:
    """Сеть ли это, а не ключ, не регион и не деньги.

    Регион (`country`, `region`) — это тоже VPN, но ключ и деньги в порядке:
    ждать тут нечего, запасной провайдер уже отработал. Деньги и ключ
    облаком не починить. Остальное — таймаут, нет соединения, сеть упала.
    """
    text = f"{type(exc).__name__} {exc}".lower()
    if "country" in text or "region" in text:
        return False
    if "insufficient" in text or "quota" in text or "balance" in text:
        return False
    if "api key" in text or "unauthorized" in text or "authentication" in text:
        return False
    return any(mark in text for mark in NETWORK_MARKS)


def _since(when: float, start: float) -> float | None:
    """Сколько прошло от `start` до отметки `when`. Нет отметки — нет числа.

    Отметки не бывает, когда облако молчало или ответ не пошёл вовсе. Тогда
    возвращаем None, а не ноль: этап не измерен.
    """
    if not when:
        return None
    return round(max(0.0, when - start), 2)


def _слова_ответа(text: str) -> list[str]:
    """Фраза словами — без регистра и знаков препинания.

    Распознавание ставит точку в конце («Да.») и иногда заглавную посреди фразы,
    а в словах согласия и отказа знаков быть не должно: иначе «да» и «да.» —
    разные слова, и половина ответов не узнавалась бы.
    """
    return re.sub(r"[^\w\s-]", " ", str(text or "").lower()).split()


# --- Диктовка заметки ---------------------------------------------------
#
# «запиши заметку» открывает диктовку, а не пишет сразу: мысль он
# рассказывает голосом несколькими фразами, и пока он говорит, каждая
# принятая фраза копится в буфер. Разбор команд и облако в это время
# пропускаются — иначе «всё» ушло бы в модель, а середина мысли —
# поговорить с ней вместо записи.
#
# Диктовка кончается тремя способами: фразой («всё», «записывай»,
# «конец заметки», «хватит»), отменой («отмена», «не записывай») или
# тишиной в DICTATION_PAUSE секунд. Тишину ловит сторож: пока он молчит,
# думая над фразой, ждать надо, а замолчал — значит закончил.

DICTATION_END = re.compile(
    r"^\s*(?:вс[её]|записывай|записывайте|конец заметки|хватит|пора|"
    r"закончил|готово)\s*[.!]*\s*$",
    re.IGNORECASE,
)
# Хвост в конце фразы: «вот про это и всё», «мысль такая, всё». Саму
# фразу надо досочистить до буфера, а «всё» — не часть мысли.
# Голое «все» в конце сюда не входит: «…как и все» — обычный конец мысли,
# и запись оборвалась бы посреди диктовки. Одно «всё» отдельной фразой
# ловит DICTATION_END.
DICTATION_TAIL = re.compile(
    r"[,\s]*(?:(?:вс[её][,\s]+)?записывай(?:те)?|конец заметки)\s*[.!]*\s*$",
    re.IGNORECASE,
)
DICTATION_CANCEL = re.compile(
    r"^\s*(?:отмена|отмени|не записывай|не записывать|отставить|забудь)\s*[.!]*\s*$",
    re.IGNORECASE,
)
# Что говорим в начале и в конце. Короткое: во время диктовки она молчит.
DICTATION_START = personas.SAY_NEUTRAL["dictation_start"][0]
DICTATION_EMPTY = personas.SAY_NEUTRAL["dictation_empty"][0]
DICTATION_CANCEL_SAY = personas.SAY_NEUTRAL["dictation_cancel"][0]
DICTATION_DONE = personas.SAY_NEUTRAL["dictation_done"][0]


