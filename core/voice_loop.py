def _trouble_words(exc: Exception) -> str:
    """Что сказать вслух, если модель не ответила."""
    text = f"{type(exc).__name__} {exc}".lower()
    if "country" in text or "region" in text:
        # Про VPN — не «отвалился»: у многих его нет вовсе, и отказ по стране
        # для них значит «нужен VPN или другой сервис» (29.09, проверка выпуска).
        return "Облако меня не пускает из этой страны — нужен VPN или другой сервис."
    if "connection" in text or "timeout" in text or "timed out" in text:
        return "Не могу достучаться до облака, проверь интернет."
    if "insufficient" in text or "quota" in text or "balance" in text:
        return "В облаке кончились деньги на счёте."
    return "Что-то сломалось в облаке, ответить не могу."


def _is_network_error(exc: Exception) -> bool:
    """Сеть ли это, а не ключ, не регион и не деньги.

    Регион (`country`, `region`) — это тоже VPN, но ключ и деньги в порядке:
    ждать тут нечего, запасной провайдер уже отработал. Деньги и ключ
    облаком не починить. Остальное — таймаут, нет соединения, сеть упала.
    """
    text = f"{type(exc).__name__} {exc}".lower()
    if "country" in text or "region" in text:
        return False
    if "insufficient" in text or "quota" in text or "balance" in text:
        return False
    if "api key" in text or "unauthorized" in text or "authentication" in text:
        return False
    return any(mark in text for mark in NETWORK_MARKS)


def _since(when: float, start: float) -> float | None:
    """Сколько прошло от `start` до отметки `when`. Нет отметки — нет числа.

    Отметки не бывает, когда облако молчало или ответ не пошёл вовсе. Тогда
    возвращаем None, а не ноль: ноль в журнале читался бы как «этот этап
    занял ноль секунд» и увёл бы хозяина не туда.
    """
    if not when:
        return None
    return round(max(0.0, when - start), 2)


