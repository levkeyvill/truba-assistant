def load_stt(model: str | None = None, quantization=СЖАТЬ_КАК_В_CONFIG):
    """Поднимает модель распознавания речи.

    Отдельной функцией, а не строкой в цикле: модель грузится в двух местах
    (при старте голоса и при смене настройки), и подмена `onnx_asr.load_model`
    в тестах должна накрывать оба. `quantization=None` — полная модель, а
    не «взять из config», поэтому для умолчания стоит отдельная метка.
    """
    import onnx_asr

    from core import onnx_opts

    return onnx_asr.load_model(
        config.STT_MODEL if model is None else model,
        quantization=config.STT_QUANTIZATION
        if quantization is СЖАТЬ_КАК_В_CONFIG else quantization,
        # Без кручения потоков: распознавание так даже быстрее (onnx_opts).
        sess_options=onnx_opts.quiet(),
    )


def stt_label(model: str, quantization) -> str:
    """Человеческое название того, что работает: модель и сжатие."""
    from core import stt_models

    spec = stt_models.find_model(model)
    # None в config — это «полная», как и "none" в настройках.
    сжатие = "полная" if quantization in (None, "none") else "сжатая"
    return f"{spec['title']} ({spec['id']}, {сжатие})"


def voice_gain() -> float:
    """Множитель сигнала по текущему уровню громкости голоса.

    Один шаг — 3 дБ, поэтому уровни отличаются на слух одинаково:
    10 → 1.0 (как было), 7 → 0.35, 1 → 0.045. Больше единицы не бывает
    никогда: на максимуме она и так захрипит.
    """
    try:
        level = int(config.VOICE_VOLUME)
    except (TypeError, ValueError):
        return 1.0
    level = max(config.VOICE_VOLUME_MIN, min(config.VOICE_VOLUME_MAX, level))
    return 10 ** (-(config.VOICE_VOLUME_MAX - level) * config.VOICE_VOLUME_STEP_DB / 20)


def _приглушить(parts, gain: float):
    """Тот же поток кусков синтеза, но каждый кусок тише в `gain` раз.

    Обёртка нужна, чтобы громкость была одна на весь путь звука: и
    потоковые куски, и целые предложения, и подтверждения голосом. На
    максимуме (gain = 1) поток идёт мимо — лишней копии сигнала не делаем.

    `close()` доходит до потока синтеза: брошенный на полпути Higgs держит
    на себе замок, и без этого он не отпустит следующую фразу.
    """
    if gain >= 1.0:
        return parts
    return _тишее(parts, gain)


def _тишее(parts, gain: float):
    """Генератор кусков, приглушённых в `gain` раз. Служебный для `_приглушить`."""
    try:
        for wave, rate in parts:
            yield wave * gain, rate
    finally:
        close = getattr(parts, "close", None)
        if close is not None:
            close()


