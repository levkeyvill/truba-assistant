def _plain(text: str) -> str:
    """Раздевает фразу до слов: без знаков, без ё, в нижнем регистре."""
    lowered = (text or "").lower().replace("ё", "е")
    return re.sub(r"\s+", " ", re.sub(r"[^а-яa-z0-9]+", " ", lowered)).strip()


def _по_порядку(услышано: list[str], сказано: list[str]) -> int:
    """Сколько слов фразы совпало с её речью в том же порядке (общая
    подпоследовательность). Слова сравниваются по началу — распознавание эха
    иногда путает окончание («костями» / «костям»)."""
    def одно(а: str, б: str) -> bool:
        return а[:6] == б[:6]

    было = [0] * (len(сказано) + 1)
    for слово in услышано:
        стало = [0]
        for j, её in enumerate(сказано):
            стало.append(было[j] + 1 if одно(слово, её) else max(было[j + 1], стало[j]))
        было = стало
    return было[-1]


def is_dismissal(text: str) -> bool:
    """Просят ли её замолчать и отстать."""
    plain = _plain(text)
    words = plain.split()
    if not words or len(words) > 20:
        return False
    if THANKS_CONTINUES.search(plain):
        return False
    # В длинной просьбе команда может быть только в конце; объяснение вида
    # «когда я говорю» не должно закрывать разговор.
    if len(words) > DISMISS_MAX_WORDS:
        if "когда я говорю" in plain or "если я говорю" in plain:
            return False
        plain = " ".join(words[-DISMISS_MAX_WORDS:])
    return bool(DISMISS_TAIL.search(plain))


# Запинки в конце фразы: фраза кончилась на «э-э-э…» и ждёт продолжения.
#
# Это не шаблоны команд, а звуки и связки, которыми человек подчёркивает,
# что говорит дальше: «слушай, этот…», «ну, значит…», «я думаю, что…».
# Набор замкнутый и маленький: держать надо ровно то, после чего человек
# тянет мысль дальше, а не любое слово, которое вдруг оказалось последним.
HESITATION = frozenset({
    "э", "ээ", "эээ", "э-э", "э-э-э", "м", "мм", "м-м", "эм", "ну",
    "этот", "эта", "это", "короче", "слушай", "типа", "значит", "вот",
    "и", "а", "но", "или", "чтобы", "что",
})
# Чистые звуки запинки — недоговорённость даже после точки: «Э-э.»
HESITATION_SOUNDS = frozenset({
    "э", "ээ", "эээ", "э-э", "э-э-э", "м", "мм", "м-м", "эм",
})


def unfinished(text: str) -> bool:
    """Недоговорённая фраза: человек остановился на полуслове.

    Признак один — конец: многоточие, запятая, тире или последнее слово из
    `HESITATION`. Середина фразы не смотрим: «ну, скажи мне… что делать»
    договорённая, если кончилась на «делать».
    """
    tail = (text or "").strip()
    if not tail:
        return False
    if tail.endswith(("...", "…", ",", "-", "–", "—")):
        return True
    # Последнее слово — без знаков препинания, в нижнем регистре, ё→е.
    last = re.sub(r"[^\w-]", "", tail.split()[-1].lower().replace("ё", "е"))
    # Точку, вопрос и восклицание распознавание ставит само, когда слышит
    # законченную фразу: «Что это?», «Ну вот.» — договорено, хотя «это» и
    # «вот» есть в наборе. После них недоговорены только звуки «э-э», «м-м».
    if tail.endswith((".", "?", "!")):
        return last in HESITATION_SOUNDS
    return last in HESITATION


