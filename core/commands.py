# --- Инструкция для пульта ------------------------------------------------
#
# Страница «Команды» в пульте собирается отсюда, а не пишется руками: иначе
# инструкция рано или поздно разойдётся с тем, что Труба понимает на самом
# деле. Даём ей ровно те поля, которые нужны странице, и в том же порядке,
# в каком идёт `COMMANDS` — порядок здесь значим (см. `understand`).


def commands_guide() -> dict:
    """Данные для страницы «Команды»: команды, окно разговора и программы.

    Три куска живут в разных местах, но человек видит их на одной странице:
    сами команды — здесь, окно разговора — в config, список программ с
    прозвищами — в apps.json. `config` и `launcher` тянутся здесь лениво:
    разбор речи идёт на каждой фразе, а страницу открывают редко.
    """
    import config
    from core import launcher

    команды = [
        {
            "id": spec.id,
            "title": spec.title,
            "examples": list(spec.examples),
            "does": spec.does,
            "arg": spec.arg,
        }
        for spec in COMMANDS
    ]
    программы = [
        {
            "title": str(app.get("title", "") or "").strip(),
            "aliases": list(launcher.aliases_of(app)),
        }
        for app in launcher.read_list()
        if str(app.get("title", "") or "").strip()
    ]
    return {
        "window": int(config.FOLLOW_UP_WINDOW),
        "commands": команды,
        "apps": программы,
    }


# --- Громкость голоса -----------------------------------------------------
#
# Только её собственный голос: и в телефоне, и в колонках. Уровень 1–10.
#
# «тихо», «помолчи», «замолчи» сюда НЕ входят: это просьба замолчать
# (voice_loop.is_dismissal, brain.BYE), а не громкость. Разводим их по разным
# словам: «тише» — про громкость, «тихо» — про молчание.
#
# Уровень распознавание пишет и цифрами, и словами — берём оба вида.
VOLUME_WORDS = {
    "один": 1, "одна": 1, "два": 2, "две": 2, "три": 3, "четыре": 4,
    "пять": 5, "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10,
}


def _volume_level(token: str) -> int | None:
    """Число из слова или цифр. None — это не про громкость («громкость колонок»)."""
    token = token.strip()
    if token.isdigit():
        value = int(token)
    else:
        value = VOLUME_WORDS.get(token, 0)
    return value if 1 <= value <= 10 else None


# --- Разбор по таблице ----------------------------------------------------
#
# Формы склеиваются в регулярку одна на форму, длинные вперёд: «сделай
# скриншот» должен сработать раньше «скриншот». `arg` — то, что команда
# просит сказать после формы, `rest` — что осталось от фразы целиком.


def _form_re(form: str) -> re.Pattern:
    return re.compile(r"^(?:" + form + r")\b\s*(?P<rest>.*)$", re.IGNORECASE)


_PATTERNS = {
    spec.id: tuple((form, _form_re(form))
                   for form in sorted(spec.forms, key=len, reverse=True))
    for spec in COMMANDS
}


def _screenshot(form, found, text, apps):
    return Command("screenshot", "Готово, скинула на телефон.")


def _moment(form, found, text, apps):
    return Command("moment", "Сохранила момент.")


def _volume(form, found, text, apps):
    if "громкость" in form and "(?P<arg>" in form:
        level = _volume_level(found.groupdict().get("arg") or "")
        if level is None:
            return None  # «громкость колонок» — это не про уровень
        # Ответ читается вслух, поэтому число словами: «Громкость пять».
        from core.speech_text import cardinal

        return Command("volume", f"Громкость {cardinal(level)}.", target=level)
    down = "тише" in form or form.startswith("убавь")
    return Command("volume", "Так тише?" if down else "Так громче?",
                   step=-1 if down else 1)


def _launch(form, found, text, apps):
    app = _match_app(found.groupdict().get("arg") or "", apps)
    if app is None:
        # Название не узнали — молчим и отдаём модели: пусть лучше
        # переспросит словами, чем запустит не то.
        return None
    return Command("launch", f"Запускаю {app.get('title')}.", target=app.get("id", ""))


def _close(form, found, text, apps):
    app = _match_app(found.groupdict().get("arg") or "", apps)
    if app is None:
        # Программа не названа («закрой разговор», «выключи голос»): закрывать
        # нечего, пусть разбирается модель.
        return None
    return Command("close", f"Закрываю {app.get('title')}.", target=app.get("id", ""))


# Хвост «на ютубе» после запроса — это не часть запроса: «открыть канал
# Корзинка на ютубе» ищет канал Корзинка, а не «Корзинка на ютубе».
YT_TAIL = re.compile(r"\s+(?:на|в|с)\s+(?:ютуб[а-яё]*|ютьюб[а-яё]*|youtube)\s*$")


def _youtube(form, found, text, apps):
    query = (found.groupdict().get("arg") or "").strip()
    query = YT_TAIL.sub("", query).strip()
    # Вид просьбы — по словам самой формы, а не по смыслу запроса.
    verb = found.groupdict().get("verb") or ""
    kind = "search" if verb in ("найди", "поищи") else "video"
    if "канал" in form or query.startswith("канал "):
        kind = "channel"
        query = re.sub(r"^канал[а-яё]*\s+", "", query)
    if not query:
        return None  # «включи на ютубе» без запроса — это запуск главной
    return Command("youtube", "", target=query, kind=kind)


def _note(form, found, text, apps):
    # Вся фраза целиком и в его же словах: «по книге Мастер и Маргарита» —
    # подсказка разделу и теме, и без неё причёсывание не поймёт, куда
    # класть. Регистр и тут не трогаем: название книги пишется с большой.
    return Command("note", "Диктуй. Скажешь «всё» — запишу.",
                   target=(text or "").strip())


def _search(form, found, text, apps):
    query = (found.groupdict().get("arg") or "").strip()
    if not query:
        return None
    return Command("search", "", target=query)


_BUILD = {
    "screenshot": _screenshot,
    "moment": _moment,
    "volume": _volume,
    "youtube": _youtube,
    "close": _close,
    "launch": _launch,
    "note": _note,
    "search": _search,
}


# --- Программа по названию вслух -------------------------------------------
#
# Слова, которые тянутся за названием и мешают его узнать.
APP_TAIL = re.compile(r"\b(мне|давай|ка|пожалуйста|на компе|на компьютере)\b")
# «Включи замену термопасты на ютубе» — это не запуск YouTube: прозвище
# программы после предлога («на ютубе», «в фоксе») означает, что человек
# говорит о месте, а не о кнопке. Такая фраза уходит модели.
APP_PREPOSITION = re.compile(r"(?:^|\s)(на|в|с|к|о|об|из)\s+$")
# Тот же предлог, но в начале имени: «включи на ютубе», «закрой в фоксе».
APP_PREPOSITION_ONLY = re.compile(r"^(?:на|в|с|к|о|об|из)\s+")


def _named_after_preposition(name: str, alias: str) -> bool:
    """Стоит ли прозвище после предлога — «на ютубе», а не «ютуб»."""
    at = name.find(alias)
    while at > 0:
        if APP_PREPOSITION.search(name[:at]):
            return True
        at = name.find(alias, at + 1)
    return False


def _match_app(name: str, apps: list[dict]) -> dict | None:
    """Ищет программу по тому, как её назвали вслух.

    Распознавание пишет латиницу как придётся — «дискорд», «фаерфокс»,
    «ютуб». Поэтому сверяем и с названием, и с прозвищами программы.
    """
    name = APP_TAIL.sub(" ", name.lower().replace("ё", "е"))
    name = re.sub(r"\s+", " ", name).strip()
    # «Включи на ютубе» — это всё тот же запуск, просто с предлогом: снимаем
    # его, когда после него осталось само имя.
    без_предлога = APP_PREPOSITION_ONLY.sub("", name)
    if без_предлога and len(без_предлога.split()) <= 2:
        name = без_предлога
    if not name:
        return None

    for app in apps or []:
        title = app.get("title", "").lower().replace("ё", "е")
        if title and (title in name or name in title):
            return app

    from core import launcher

    for app in apps or []:
        if any(alias in name and not _named_after_preposition(name, alias)
               for alias in launcher.aliases_of(app)):
            return app
    return None


def understand(text: str, apps: list[dict] | None = None) -> Command | None:
    """Разбирает фразу по таблице. None — это не команда, пусть модель."""
    text = (text or "").strip()
    if not text:
        return None
    # Вопрос — это разговор, а не приказ: «ты сделала скриншот?» не должен
    # снимать экран второй раз.
    if "?" in text:
        return None
    if len(text.split()) > MAX_WORDS:
        return None

    clean = normalize(text)
    if not clean:
        return None

    for spec in COMMANDS:
        for form, pattern in _PATTERNS[spec.id]:
            found = pattern.match(clean)
            if found is None:
                continue
            # У команды без аргумента после формы должно быть пусто:
            # «снимок экрана в заметках» — это уже просьба записать, а не снять.
            if not spec.arg and found.group("rest"):
                continue
            order = _BUILD[spec.id](form, found, text, apps or [])
            if order is not None:
                return order
    return None
