    id: str
    # Как это называется по-человечески.
    title: str
    # Формы начала фразы; аргумент, если он есть, — группой `arg`.
    forms: tuple
    # Живые примеры: разбираются в эту команду (таблица проверяет себя).
    examples: tuple
    # Что произойдёт, одной фразой.
    does: str
    # Что идёт после формы. Пусто — аргумента нет.
    arg: str


