# «Свой» — характер, который пишет сам человек; готовые от него не меняются.
# Готового текста нет: пульт начинает его с копии выбранного стиля. Быстрые
# фразы — спокойные: без мата они подходят к любому тексту.
CUSTOM = "custom"
PRESETS[CUSTOM] = {
    "title": "Свой",
    "hint": "Твой характер: начинается с копии выбранного, готовые не меняются",
    "bye": PRESETS["calm"]["bye"],
    "ready": PRESETS["calm"]["ready"],
    "wait": PRESETS["calm"]["wait"],
    "say": PRESETS["calm"]["say"],
}

_say_last: dict[tuple[str | None, str], str] = {}
_say_lock = threading.Lock()


def say(key: str, preset: str | None, **fields) -> str:
    """Готовый ответ по действию и характеру без повтора подряд."""
    phrases = PRESETS.get(preset, {}).get("say", {}).get(key) or SAY_NEUTRAL[key]
    slot = (preset, key)
    with _say_lock:
        choices = [phrase for phrase in phrases if phrase != _say_last.get(slot)]
        phrase = random.choice(choices or phrases)
        _say_last[slot] = phrase
    return phrase.format(**fields)


def wait_phrase(kind: str, preset: str | None) -> str:
    """Короткая фраза ожидания по делу и выбранному характеру."""
    phrases = PRESETS.get(preset, {}).get("wait", {}).get(kind)
    return random.choice(phrases or WAIT_NEUTRAL.get(kind) or WAIT_NEUTRAL["find"])


def all_wait_phrases() -> frozenset:
    """Все фразы ожидания для голосового цикла."""
    sets = [WAIT_NEUTRAL] + [spec["wait"] for spec in PRESETS.values()]
    return frozenset(phrase for phrases in sets for variants in phrases.values()
                     for phrase in variants)


def get(preset_id) -> dict:
    """Характер по id; неизвестный — фирменный."""
    return PRESETS.get(str(preset_id or ""), PRESETS[DEFAULT])


def valid(preset_id) -> str:
    """Id, который можно хранить в настройках: неизвестный → по умолчанию."""
    key = str(preset_id or "")
    return key if key in PRESETS else DEFAULT


def text(preset_id) -> str:
    """Текст характера. Нет файла — пустая строка, без исключения."""
    path = TEXTS / f"{valid(preset_id)}.md"
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def bye_words(preset_id) -> dict:
    """Быстрые ответы на прощание и «помолчи» — по виду прощания."""
    return get(preset_id)["bye"]


def ready_words(preset_id) -> tuple:
    """Что сказать, когда голос загрузился и слушает."""
    return get(preset_id)["ready"]


def catalog(with_text: bool = False) -> list[dict]:
    """Список для пульта: id, название, пояснение (и текст, если нужен)."""
    out = []
    for key, spec in PRESETS.items():
        item = {"id": key, "title": spec["title"], "hint": spec["hint"]}
        if with_text:
            item["text"] = text(key)
        out.append(item)
    return out
