def get(preset_id) -> dict:
    """Характер по id; неизвестный — фирменный."""
    return PRESETS.get(str(preset_id or ""), PRESETS[DEFAULT])


def valid(preset_id) -> str:
    """Id, который можно хранить в настройках: неизвестный → по умолчанию."""
    key = str(preset_id or "")
    return key if key in PRESETS else DEFAULT


def text(preset_id) -> str:
    """Текст характера. Нет файла — пустая строка, без исключения."""
    path = TEXTS / f"{valid(preset_id)}.md"
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def bye_words(preset_id) -> dict:
    """Быстрые ответы на прощание и «помолчи» — по виду прощания."""
    return get(preset_id)["bye"]


def ready_words(preset_id) -> tuple:
    """Что сказать, когда голос загрузился и слушает."""
    return get(preset_id)["ready"]


def catalog(with_text: bool = False) -> list[dict]:
    """Список для пульта: id, название, пояснение (и текст, если нужен)."""
    out = []
    for key, spec in PRESETS.items():
        item = {"id": key, "title": spec["title"], "hint": spec["hint"]}
        if with_text:
            item["text"] = text(key)
        out.append(item)
    return out
