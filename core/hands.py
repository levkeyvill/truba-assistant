def run_close_document(arguments: str, on_event: Event | None = None) -> str:
    """Закрывает открытый документ по названию. Строка — для сообщения tool.

    Окно получает `WM_CLOSE` — это как крестик, поэтому несохранённый
    документ программа спросит сама, а процесс не убивается. Нашлось
    несколько окон с таким названием — не закрываем ничего, отдаём
    заголовки: выбирает хозяин, и это его второй круг.
    """
    emit = _rem_emit(on_event)
    args = _rem_args(arguments)
    if args is None:
        return _error("аргументы не разобрались как JSON")

    название = str(args.get("name") or "").strip()
    if not название:
        return _error("название документа не названо — спроси хозяина, что закрыть")

    from core import documents

    try:
        что = documents.close_window_of(название)
    except Exception as exc:
        emit("close_failed", название)
        return _error(f"не закрыла: {type(exc).__name__}: {exc}")

    кандидаты = [str(one) for one in (что.get("candidates") or [])]
    if кандидаты:
        emit("close_failed", ", ".join(кандидаты))
        return _ok(ok=False, count=len(кандидаты), candidates=кандидаты,
                   text=str(что.get("text") or ""))
    if not что.get("ok"):
        emit("close_failed", название)
        return _error(str(что.get("text") or "не закрыла документ"))
    emit("closed", что.get("title"))
    remember_done(CLOSE_DOC_NAME, arguments)
    title = str(что.get("title") or "")
    name = str(что.get("name") or title)
    return _ok(ok=True, title=title, name=name,
               text=personas.say("doc_close", config.PERSONA_PRESET, name=name))


def run_folder(arguments: str, on_event: Event | None = None) -> str:
    """Открывает стандартную папку или любую папку по названию. Строка — для tool.

    Стандартная папка и диск — `core/folders.py` и общий формат строки журнала.
    Любая другая папка ищется по названию тем же обходом, что и файлы
    (`core/files.py`). Пользовательские папки открывает `launch_app`.
    """

    def emit(kind: str, payload) -> None:
        if on_event is not None:
            try:
                on_event(kind, payload)
            except Exception:
                pass

    try:
        args = json.loads(arguments or "{}")
        if not isinstance(args, dict):
            raise ValueError
    except ValueError:
        return _error("аргументы не разобрались как JSON")

    folder_id = str(args.get("folder") or "").strip()
    if not folder_id:
        return _run_folder_by_name(args, arguments, emit)

    what = folders.open_folder(folder_id)
    emit("folder" if what.get("ok") else "folder_failed",
         folders.title_of(folder_id))
    if not what.get("ok"):
        return _error(str(what.get("text") or "папку не открыла"))
    remember_done(FOLDER_NAME, arguments)
    # Путь в облако не отдаём: в нём имя пользователя Windows, модели он ни к чему.
    return _ok(ok=True, folder=folder_id, text=what["text"])


def _run_folder_by_name(args: dict, arguments: str, emit) -> str:
    """Папка по названию: ищем папки тем же обходом, что и файлы.

    Одна нашлась — открываем, несколько равных — спрашиваем хозяина (сам выбрать
    нельзя: названы одинаково), ни одной — честно говорим об этом.
    """
    from core import files

    имя = str(args.get("name") or "").strip()
    if not имя:
        return _error("название папки не названо — спроси хозяина, какую открыть")
    try:
        что = files.find(имя, str(args.get("drive") or "").strip(),
                         folders_only=True)
    except Exception as exc:
        return _error(f"не искала папку: {type(exc).__name__}: {exc}")
    found = list(что.get("found") or [])
    if not found:
        emit("folder_failed", имя)
        return _error(str(что.get("why") or "не нашла папку"))
    if len(found) > 1:
        # Одинаково названы — открывать наугад нельзя, хозяин выберет сам.
        emit("folder_failed", ", ".join(one.name for one in found))
        return _ok(ok=False, count=len(found),
                   searched_all=bool(что.get("searched_all")),
                   candidates=[{"name": one.name,
                                "folder": files.папка_пути(one)} for one in found],
                   **_приблизительно(что),
                   text=f"Нашлось несколько папок «{имя}» — какую открыть?")
    один = found[0]
    открыт = files.open_file(один)
    emit("folder" if открыт.get("ok") else "folder_failed", один.name)
    if not открыт.get("ok"):
        return _error(str(открыт.get("text") or "не открыла папку"))
    remember_done(FOLDER_NAME, arguments)
    # Путь в облако целиком не идёт: в нём имя пользователя Windows.
    return _ok(ok=True, count=1, name=один.name, path=files.короткий(один),
               folder=files.папка_пути(один), **_приблизительно(что),
               text=str(открыт.get("text")))


def _приблизительно(что: dict) -> dict:
    """Поле `approx` для ответа, когда нашли нестрогим кругом.

    Название могло прийти от распознавания кривым, и модели это полезно знать:
    найдено не буквально то, что сказали.
    """
    return {"approx": True} if что.get("approx") else {}


def run_find_file(arguments: str, on_event: Event | None = None) -> str:
    """Ищет файл по названию и, если просили, открывает. Строка — для tool.

    Пути в облако уходят без имени пользователя Windows (`core/files.py`): в
    пути имя человека, а модели оно ни к чему. Найдено одно — имя, путь и папка;
    открывали — ещё и готовая фраза для голоса. Нашлось несколько — имена с
    папками, чтобы модель переспросила, а не выбрала наугад.
    """
    emit = _rem_emit(on_event)
    args = _rem_args(arguments)
    if args is None:
        return _error("аргументы не разобрались как JSON")

    слова = str(args.get("name") or "").strip()
    if not слова:
        return _error("название файла не названо — спроси хозяина, что найти")

    from core import files

    try:
        что = files.find(слова, str(args.get("drive") or "").strip())
    except Exception as exc:
        return _error(f"не искала файл: {type(exc).__name__}: {exc}")
    found = list(что.get("found") or [])
    if not found:
        emit("file_missing", слова)
        return _error(str(что.get("why") or "не нашла файла"))

    if len(found) > 1:
    # При нескольких совпадениях сначала нужно уточнить выбор.
        emit("file_found", ", ".join(one.name for one in found))
        return _ok(ok=True, count=len(found),
                   searched_all=bool(что.get("searched_all")),
                   candidates=[{"name": one.name,
                                "folder": files.папка_пути(one)} for one in found],
                   **_приблизительно(что),
                   text="", why=str(что.get("why") or ""))

    один = found[0]
    if not bool(args.get("open")):
        emit("file_found", один.name)
        return _ok(ok=True, count=1, name=один.name,
                   path=files.короткий(один), folder=files.папка_пути(один),
                   searched_all=bool(что.get("searched_all")), **_приблизительно(что),
                   text="", why=str(что.get("why") or ""))

    открыт = files.open_file(один)
    if not открыт.get("ok"):
        emit("file_found", f"{один.name} — {открыт.get('text')}")
        return _error(str(открыт.get("text") or "не открыла файл"))
    emit("file_opened", один.name)
    remember_done(FIND_NAME, arguments)
    return _ok(ok=True, count=1, opened=True, name=один.name,
               path=files.короткий(один), folder=files.папка_пути(один),
               **_приблизительно(что),
               text=str(открыт.get("text")))


