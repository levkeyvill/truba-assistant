def _title_of(app_id: str, apps: list[dict]) -> str:
    for app in apps:
        if str(app.get("id", "")).strip() == app_id:
            return str(app.get("title", "")).strip() or app_id
    return app_id


def _result_dict(results: list[str] | None, index: int) -> dict:
    """Разобранный ответ инструмента по номеру, или пустой словарь."""
    if not results or index >= len(results):
        return {}
    try:
        data = json.loads(results[index])
    except (TypeError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def _result_text(results: list[str] | None, index: int) -> str:
    """Поле `text` из ответа инструмента по номеру, или пусто."""
    return str(_result_dict(results, index).get("text", ""))


def _is_repeat(results: list[str] | None, index: int) -> bool:
    """Отвечает ли инструмент «уже сделано», а не «сделано»."""
    return bool(_result_dict(results, index).get("repeat"))


def _lower_first(text: str) -> str:
    # Только русское слово: «Закрыла» → «закрыла», а «Telegram» — название,
    # его не трогаем.
    if text and "А" <= text[0] <= "Я":
        return text[:1].lower() + text[1:]
    return text


def _join(parts: list[str]) -> str:
    """Склеить действия без точки и заглавной буквы посреди фразы."""
    if len(parts) == 1:
        return parts[0]
    return " и ".join([parts[0]] + [_lower_first(p) for p in parts[1:]]) + "."


def confirm(calls: list[dict], apps: list[dict] | None = None,
            results: list[str] | None = None) -> str:
    """Сказать о выполненных действиях без второго круга модели."""
    if not calls:
        return ""
    known = read_list() if apps is None else apps
    one = len(calls) == 1
    parts: list[str] = []
    for call in calls:
        # Вид чтения определяет, нужен ли второй круг модели.
        forms = confirm_forms(call)
        if forms is None:
            return ""
        # Несколько найденных папок выбирает хозяин во втором круге.
        if _result_dict(results, len(parts)).get("candidates"):
            return ""
        try:
            args = json.loads(call.get("args") or "{}")
        except ValueError:
            return ""
        if not isinstance(args, dict):
            return ""
        title = _title_of(str(args.get("app", "")).strip(), known)
        # Ответ инструмента хранит результат, включая отказ и повтор.
        said = _result_text(results, len(parts))
        # Повтор нельзя подтверждать словами о новом действии.
        if _is_repeat(results, len(parts)):
            if not said:
                return ""
            if call.get("name") in (NAME, CLOSE_NAME):
                key = "launch_already" if call.get("name") == NAME else "close_already"
                said = personas.say(key, config.PERSONA_PRESET, app=title)
            parts.append(said)
            continue
        if call.get("name") in (CLOSE_NAME, YT_NAME) and "не запущен" in said:
            if not said:
                return ""
            parts.append(said.rstrip("."))
            continue
        if call.get("name") in (SHOT_NAME, MOMENT_NAME):
            key = "screenshot" if call.get("name") == SHOT_NAME else "moment"
            parts.append(personas.say(key, config.PERSONA_PRESET))
            continue
        if call.get("name") in (NAME, CLOSE_NAME):
            key = "launch" if call.get("name") == NAME else "close"
            parts.append(said or personas.say(key, config.PERSONA_PRESET, app=title))
            continue
        if "{text}" in forms[0]:
            if not said:
                return ""
            # Точка убирается только при склейке нескольких действий.
            parts.append(said)
            continue
        # Запасной шаблон для новых инструментов без поля `text`.
        parts.append((random.choice(forms) if one else forms[0]).format(title=title))
    if one:
        return parts[0]
    return _join([part.rstrip(".") for part in parts])


