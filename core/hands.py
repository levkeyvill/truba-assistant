def judge_says_yes(text: str) -> bool:
    """Ответ судьи: «да» — True. Всё остальное (молчание, «не знаю») — False."""
    answer = (text or "").strip().lower()
    answer = answer.strip(" \t\r\n.,!?:;«»\"'()-—…")
    return answer.startswith("да")


