r"""История поиска: что она на самом деле искала в интернете.

Карточка на телефоне показывает только последний ответ (`last_queries` в
`core/brain.py`), а хозяину нужен список за день: «что ты там искала?». Поэтому
каждый **успешный** запрос к поисковику ложится сюда, отдельным маленьким
файлом в `data/`, и переживает перезапуск.

Одна запись — один элемент списка:

    {"id": "9f1c…", "at": "2026-09-30T18:04:11+05:00", "query": "курс доллара цб"}

Сюда попадает ровно то, что ушло в поисковик (`web_search`), и только когда он
ответил. Не слова хозяина (их она переписывает сама, и в историю шло бы то, что
он и не искал), не попытка без результатов и не открытие старого запроса из
истории. Источников, ответов, ключей и личных файлов тут нет и быть не должно:
это список слов, которые ушли в интернет, а не переписка.

**Одна запись — одна попытка хозяина.** Внутри одного ответа модель может
сходить в поисковик несколько раз с переформулированными запросами, и это всё
одна и та же запись: главный запрос лежит в `query`, остальные — в `queries`.
Телефон показывает только `query`. Отдельный будущий поиск того же вопроса —
новая запись, как и раньше.

**`id` у записи есть, и он непредсказуемый**: телефон убирает строку по нему,
а не по тексту и не по номеру в списке (повтор запроса и параллельная запись
делают и то, и другое негодным ключом). Старые записи без `id` не теряются:
при первом чтении им проставляется свой, и файл переписывается — иначе их не
было бы чем удалять. Никаких файлов по `id` не открывается: это только ключ
списка, а телефон не присылает ни путей, ни адресов.

Путь берётся переменной модуля `PATH`, а не константой: тесты подменяют её на
временную папку (см. `tests/test_data_guard.py`), живая `data/` остаётся
нетронутой.
"""

import json
import re
import threading
import uuid
from datetime import datetime

import config

PATH = config.DATA_DIR / "search_history.json"

# Сколько запросов держим. Больше ста — это уже не история за день, а свалка:
# телефон показывает список, а хозяин листает его боковым зрением.
MAX = 100
# Длина запроса. Модель пишет в поисковик короткое, а обрезать надо: в файл не
# должно попасть ничьё длинное рассуждение, если она вдруг впихнёт его в `query`.
QUERY_MAX = 200
# Сколько прочих запросов одного ответа храним. Список телефону они не нужны —
# нужны, чтобы «что ты там искала» можно было прочитать и в файле.
ALSO_MAX = 8

# `id` — 32 hex-символа `uuid4`. Проверяем строго: по `id` ничего не открывается,
# но мусор с телефона (путь, url, чужой id) и подавно не должен попасть в файл.
_ID = re.compile(r"\A[0-9a-f]{32}\Z")

# Запись идёт из голосового цикла и из чата пульта — это два потока, а файл
# один. RLock, потому что пишем под тем же замком, каким читаем.
_LOCK = threading.RLock()


def _now() -> datetime:
    """Местное время с поясом — как у будильника (core/reminders.py)."""
    return datetime.now().astimezone()


def _чистый(текст) -> str:
    """Запрос без лишних пробелов и не длиннее `QUERY_MAX`."""
    return " ".join(str(текст or "").split())[:QUERY_MAX]


def _id_годен(значение) -> bool:
    """Наш `id` — 32 hex-символа. Чужой (путь, url, слово) не проходит."""
    return bool(_ID.fullmatch(str(значение or "")))


def _проставить_id(items: list[dict]) -> bool:
    """Раздать `id` записям, у которых его нет. Ответ — менялся ли файл.

    Так мигрируют старые записи: без `id` их нечем было бы удалить с телефона.
    Повтор и мусор в `id` тоже заменяем — иначе `delete` снёс бы не ту строку.
    """
    было = False
    видел: set[str] = set()
    for one in items:
        ident = str(one.get("id", "") or "")
        if not _id_годен(ident) or ident in видел:
            one["id"] = uuid.uuid4().hex
            было = True
        видел.add(one["id"])
    return было


def _read() -> list[dict]:
    """Все записи из файла, старейшие первыми. Битый файл — пустой список."""
    try:
        data = json.loads(PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    if not isinstance(data, list):
        return []
    return [one for one in data if isinstance(one, dict)]


def _write(items: list[dict]) -> None:
    """Запись через временный файл: оборванная запись не должна выглядеть
    как настоящий запрос (как в `core/reminders.py`)."""
    path = PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    partial = path.with_name(path.name + ".part")
    try:
        partial.write_text(
            json.dumps(items, ensure_ascii=False, indent=1), encoding="utf-8"
        )
        partial.replace(path)
    except Exception:
        try:
            partial.unlink(missing_ok=True)
        except OSError:
            pass
        raise


def add(query: str, when=None, also: list | None = None) -> dict | None:
    """Запомнить запрос, который реально ушёл в поисковик.

    Одна попытка — одна запись. `also` — остальные запросы того же ответа
    (`Brain._search_first` собирает их, переформулируя вопрос): в историю они
    идут одним полем, а не отдельными строками, иначе хозяин увидел бы один
    свой вопрос четырьмя записями.

    Пустая строка и пробелы — не запрос, а мусор: возвращаем `None`.
    Повтор запроса **позже** — отдельное событие: хозяин мог поискать то же
    самое ещё раз, и история должна показывать оба реальных похода в интернет.

    Ответ — записанная запись или `None`.
    """
    текст = _чистый(query)
    if not текст:
        return None
    прочие: list[str] = []
    for один in list(also or []):
        чужой = _чистый(один)
        # Главный запрос в `queries` не дублируем: он и так в `query`.
        if чужой and чужой != текст and чужой not in прочие:
            прочие.append(чужой)
        if len(прочие) >= ALSO_MAX:
            break
    момент = when if when is not None else _now()
    with _LOCK:
        items = _read()
        запись = {
            "id": uuid.uuid4().hex,
            "at": момент.isoformat(timespec="seconds")
            if hasattr(момент, "isoformat") else str(момент),
            "query": текст,
        }
        if прочие:
            запись["queries"] = прочие
        items.append(запись)
        # Старое уходит: файл маленький и не должен расти без конца.
        _write(items[-MAX:])
    return запись


def delete(entry_id: str) -> bool:
    """Убрать одну запись по `id`. Ответ — убрали что-нибудь или нет.

    Строго по `id`: тот же запрос может лежать в истории дважды, и убирается
    ровно та строка, которую хозяин ткнул, а не все с таким текстом. Чужой
    `id` (путь, url, пусто) — отказ, а не «убрать последнюю»: по `id` у нас
    ничего не открывается, только сравниваем строки в уже прочитанном списке.
    """
    if not _id_годен(entry_id):
        return False
    with _LOCK:
        items = _read()
        left = [one for one in items if str(one.get("id", "")) != str(entry_id)]
        if len(left) == len(items):
            return False
        _write(left)
    return True


def clear() -> int:
    """Очистить всю историю. Ответ — сколько записей убрано.

    Под тем же замком и той же атомарной записью, что `add` и `delete`: файл
    либо прежний, либо пустой, но не половина списка.
    """
    with _LOCK:
        items = _read()
        if items:
            _write([])
        return len(items)


def entries(limit: int = MAX) -> list[dict]:
    """Записи новыми сверху: так телефон их и показывает.

    Ответ — список словарей `{"id", "at", "query"}`. `id` обязателен: телефон
    убирает строку по нему. Битая запись (не словарь или без запроса) молча
    пропускается: список на телефоне лучше пустым, чем с мусором. Прочие
    запросы ответа (`queries`) сюда не идут — рисуется только главный, а файл
    хранит всё.
    """
    сколько = max(1, min(int(limit or MAX), MAX))
    out: list[dict] = []
    with _LOCK:
        items = _read()
        # Старые записи без `id` получают его здесь и переписываются: иначе
        # телефон показал бы строку, которую нечем удалить.
        if _проставить_id(items):
            # Если диск не принял миграцию, не отдаём телефону временные id:
            # после следующего чтения они сменятся, и «Удалить» не сработает.
            # WebRuntime покажет ошибку чтения списка и даст попробовать ещё.
            _write(items[-MAX:])
        for one in reversed(items):
            текст = _чистый(one.get("query", ""))
            if not текст:
                continue
            out.append({"id": str(one.get("id", "")), "at": str(one.get("at", "")),
                        "query": текст})
            if len(out) >= сколько:
                break
    return out
