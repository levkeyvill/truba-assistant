def find_input_device(name: str | None = None, hostapi: str | None = None):
    """Находит микрофон по подстроке имени, предпочитая указанный звуковой API.

    Пустое имя или устройство, которого нет, — это не поломка, а обычное дело
    чужого компьютера: у автора звуковая карта с названием, а у другого человека
    системный микрофон. Поэтому в обоих случаях берётся устройство ввода по
    умолчанию, иначе голос не заработал бы ни у кого, кроме автора.

    Возвращает (индекс, описание) или (None, None), если ввода нет вовсе.
    """
    # Имя и API — из настроек в момент вызова: значение по умолчанию у
    # аргумента Python считает один раз при загрузке модуля, и выбранное
    # в пульте устройство никогда бы не дошло.
    name = MIC_NAME if name is None else name
    hostapi = PREFERRED_HOSTAPI if hostapi is None else hostapi
    import sounddevice as sd

    if str(name or "").strip():
        candidates = []
        for idx, dev in enumerate(sd.query_devices()):
            if dev["max_input_channels"] < 1:
                continue
            if name.lower() not in dev["name"].lower():
                continue
            api = sd.query_hostapis(dev["hostapi"])["name"]
            # Предпочитаем нужный API, среди равных — с большей частотой дискретизации.
            priority = (hostapi.lower() in api.lower(), dev["default_samplerate"])
            candidates.append((priority, idx, dev, api))

        if candidates:
            candidates.sort(key=lambda c: c[0], reverse=True)
            _, idx, dev, api = candidates[0]
            return idx, describe_device(dev, api)
        # Имени такого нет — падаем на системный микрофон, а не в отказ.
    return default_device(input=True, hostapi=hostapi)


