def describe_device(dev: dict, api: str) -> str:
    """Человеческое описание устройства — им же заполняем журнал."""
    rate = int(dev.get("default_samplerate") or 0)
    return f"{dev['name']} ({api}, {rate} Гц)"


def default_device(input: bool = True, hostapi: str = PREFERRED_HOSTAPI):
    """Устройство по умолчанию — то, чем система сама пишет и играет.

    Windows сообщает его сама — спрашиваем тот же звуковой API, что и список
    для пульта (`_default_index`): у живого списка автора `sd.default.device`
    был `-1`, и пустое имя микрофона уводило голос на «Microsoft Sound
    Mapper» вместо его звуковой карты. Если система не сообщает (нет WASAPI,
    API молчит, `-1` или `None`) — берём первое подходящее, предпочитая нужный
    API: тот же выбор, что и при поиске по имени.
    """
    import sounddevice as sd

    ключ = "max_input_channels" if input else "max_output_channels"
    chosen = _default_index(input, _предпочтительные_api(sd, input))
    if chosen is not None:
        try:
            info = sd.query_devices(chosen)
        except Exception:
            info = None
        if info is not None and info[ключ] > 0:
            api = sd.query_hostapis(info["hostapi"])["name"]
            return int(chosen), describe_device(info, api)

    candidates = []
    for idx, dev in enumerate(sd.query_devices()):
        if dev[ключ] < 1:
            continue
        api = sd.query_hostapis(dev["hostapi"])["name"]
        priority = (hostapi.lower() in api.lower(), dev["default_samplerate"])
        candidates.append((priority, idx, dev, api))
    if not candidates:
        return None, None
    candidates.sort(key=lambda c: c[0], reverse=True)
    _, idx, dev, api = candidates[0]
    return idx, describe_device(dev, api)
