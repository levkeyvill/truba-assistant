def _list_devices(input: bool) -> list[dict]:
    """Список устройств для пульта — ровно такой, как в «Параметрах звука».

    Одно и то же устройство Windows показывает в четырёх API (WASAPI, MME,
    DirectSound, WDM-KS), и MME обрезает имя до 31 знака: в списке пульта
    это были и «Яндекс музыка (Virtual Audio Ca)», и «Microsoft Sound
    Mapper» рядом с настоящим именем того же устройства. Поэтому если хоть
    одно устройство есть в предпочтительном API (у нас это WASAPI), список
    берётся только из него: там имена полные, и Windows их не дублирует.
    Предпочтительного API нет (старый звук, чужая система) — ведём себя
    как раньше: все API, из дублей остаётся лучший.
    """
    import sounddevice as sd

    ключ = "max_input_channels" if input else "max_output_channels"
    порядок: list[str] = []
    лучшие: dict[str, tuple] = {}
    предпочтительные: set[int] = set()   # номера API с нужными каналами
    for idx, dev in enumerate(sd.query_devices()):
        if dev[ключ] < 1:
            continue
        номер = int(dev["hostapi"])
        api = str(sd.query_hostapis(номер)["name"])
        свой_api = PREFERRED_HOSTAPI.lower() in api.lower()
        if свой_api:
            предпочтительные.add(номер)
        # Чем больше вес — тем лучше кандидат. Первый по счёку при равенстве.
        вес = (свой_api, -idx)
        item = {
            "index": idx,
            "name": str(dev["name"]),
            "api": api,
            "channels": int(dev[ключ]),
            "rate": int(dev.get("default_samplerate") or 0),
            "default": False,
            "_api": номер,
        }
        name = item["name"]
        прежний = лучшие.get(name)
        if прежний is None:
            лучшие[name] = (вес, item)
            порядок.append(name)
        elif вес > прежний[0]:
            лучшие[name] = (вес, item)
    устройства = [лучшие[name][1] for name in порядок]
    # Предпочтительный API есть — берём список только из него, иначе хозяин
    # увидел бы двадцать три микрофона вместо шести и не понял бы, где его.
    if предпочтительные:
        устройства = [у for у in устройства if у.pop("_api") in предпочтительные]
    else:
        for у in устройства:
            у.pop("_api", None)
    default = _default_index(input, предпочтительные)
    for у in устройства:
        у["default"] = default is not None and int(default) == у["index"]
    return устройства


def _default_index(input: bool, предпочтительные: set | None = None):
    """Индекс устройства по умолчанию или None, если система его не назвала.

    Windows сообщает его сама, но не так, как это делал `sd.default.device`:
    у живого списка автора он всегда был `-1` и с индексами не совпадал
    никогда, поэтому «по умолчанию» не достался ни одному устройству.
    Настоящее имя устройства по умолчанию лежит в самом API: у WASAPI это
    `default_input_device` / `default_output_device`. Спрашиваем сначала
    предпочтительный API, а его нет — тот, которым система сама пользуется
    (`sd.default.hostapi`). Молчит и он — отдаём `sd.default.device`, как
    раньше: пусть лучше первое подходящее, чем ничего.
    """
    import sounddevice as sd

    ключ = "default_input_device" if input else "default_output_device"
    for номер in _api_порядок(sd, предпочтительные):
        try:
            названный = _индекс(sd.query_hostapis(номер).get(ключ))
        except Exception:
            continue
        if названный is not None:
            return названный
    try:
        chosen = sd.default.device[0] if input else sd.default.device[1]
    except Exception:
        return None
    return _индекс(chosen)


def _api_порядок(sd, предпочтительные) -> list:
    """Звуковые API по очереди: сначала WASAPI, потом тот, что у системы.

    Номера берём из `query_hostapis()`, а не из устройств: у Windows
    `default_input_device` знает именно API, и он умеет назвать устройство
    по умолчанию даже там, где в списке устройств его нет.
    """
    try:
        все_api = list(sd.query_hostapis())
    except Exception:
        все_api = []
    порядок: list[int] = []
    for номер in sorted(предпочтительные or ()):
        if 0 <= номер < len(все_api) or not все_api:
            порядок.append(номер)
    try:
        системный = _индекс(getattr(sd.default, "hostapi", None))
    except Exception:
        системный = None
    if системный is not None and системный not in порядок:
        порядок.append(системный)
    return порядок


def _индекс(значение):
    """Индекс из ответа Windows. `None` или `-1` — система его не назвала."""
    try:
        число = int(значение)
    except (TypeError, ValueError):
        return None
    return число if число >= 0 else None


def _предпочтительные_api(sd, input: bool) -> set:
    """Номера звуковых API, где нужные устройства уже есть.

    Пусто — такого API на компьютере нет, и тогда выбор по умолчанию
    спрашивается у того API, которым система сама пользуется.
    """
    ключ = "max_input_channels" if input else "max_output_channels"
    свои: set[int] = set()
    for dev in sd.query_devices():
        if dev[ключ] < 1:
            continue
        номер = int(dev["hostapi"])
        try:
            api = str(sd.query_hostapis(номер)["name"])
        except Exception:
            continue
        if PREFERRED_HOSTAPI.lower() in api.lower():
            свои.add(номер)
    return свои


